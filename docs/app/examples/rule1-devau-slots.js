// deva- «бог» (тематическая основа муж. рода) + au (окончание им./вин./
// зват. падежа двойственного числа) → devau «(оба) бога» — правило 1 на
// слот-движке.
//
// Источник (Whitney §127, Pāṇini 6.1.88 vṛddhir eci): единая таблица
// комбинаций a+простой гласный→гуна (правило 2) / a+дифтонг→вриддхи
// (правило 1). Обе строки — ОДНА и та же операция Pāṇini (адхикара 6.1.84
// ekaḥ pūrvaparayoḥ, «один [звук заменяет] предыдущий и последующий») —
// РАЗЛИЧИЕ только в том, КАКАЯ ступень применяется к правому гласному:
// гуна к простому, вриддхи к дифтонгу. Для пары a+au результат вриддхи
// СОВПАДАЕТ по написанию с au (au — уже сама предельная, вриддхи-ступень
// ряда u/o/au, повышать больше некуда) — но ОПЕРАЦИЯ применяется та же
// самая, просто с вырожденным (незаметным на глифе) результатом.
//
// МЕХАНИКА (третий пересмотр, прямой запрос пользователя): «мы же
// сливаем их» — a и au ОБА физически сдвигаются РОВНО НА ОДИН СЛОТ
// навстречу друг другу, на уже существующий зазор между ними (не «одна
// едет, другая ждёт», и не куда-то «между» позициями — зазор САМ по себе
// целая слотовая позиция). Там они сливаются — тот же приём merge, что и
// a+a→ā в правиле 7 (один кубик доезжает и исчезает точно в момент
// контакта, вспышка на выжившем). Раскладка:
//   d(1) e(2) v(3) [a](4) [зазор](5) [au](6)
// a и au ОБА approach'ем сдвигаются на слот 5 (дистанция 1.0 каждая, не
// 2 — половину исходного расстояния проходит каждая сторона), встречаются
// там одновременно, merge довершает слияние. Результат — СРАЗУ золотой
// (вриддхи), без паузы-в-истинном-цвете между слиянием и огласовкой
// (anticipateDur:0 у transform — своя пауза-осознание тут не нужна,
// вспышка merge её уже даёт). Позиции 4 и 6 после слияния пустуют — их
// закрывает финальный approach в самом конце, когда результат уже готов.
//
// У двойного оборота (вриддхи) УЖЕ есть встроенная «пустая» фаза (буква
// пропадает на середине первого оборота и не появляется вплоть до
// середины второго — см. applyTransform, revealDeg для spinTurns:2) — она
// и показывает «au не осталось здесь, исчезло, а затем возникла форма
// вриддхи», ничего дополнительно строить не нужно.
//
// РЕАЛЬНАЯ НАХОДКА (движок, при подготовке этого примера, поймано
// численной симуляцией ДО сдачи): transform крутящегося кубика ПИШЕТ
// position.x = slotX(op.at) каждый кадр — если кубик до этого физически
// переехал (как здесь, слился на слоте 5, а его ключ в cubes{} остался
// прежним, 6), transform без поправки сдёрнул бы его ОБРАТНО на слот 6.
// Добавлено новое необязательное поле `TransformOp.atX` — явная мировая
// позиция вращения/посадки, когда она отличается от slotX(at). Также
// найден и исправлен смежный баг в `applyMerge`: спад вспышки шёл
// НАВСЕГДА (без верхней границы), и на кадрах спустя много секунд после
// слияния лез в material уже кручащегося (и не раз переприсвоенного)
// кубика — добавлен одноразовый `_decayDone`.
//
// a — РАВНОЗНАЧНЫЙ участник eka-ādeśa (обе стороны вместе заменяются
// одним результатом, Pāṇini 6.1.84), не «условие, которое исчезает» —
// поэтому её слияние тоже подписано (label:'ekādeśa' на merge), а сама
// вриддхи — отдельной подписью (label:'vṛddhi' на transform).
import { mountSlotExample, centeredStart, TRANSFORM_KIND, slotX } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 4-буквенному слову «devau»:
// centeredStart(4)=3.
const START = centeredStart(4); // = 3
//   START+0 = d ⎫
//   START+1 = e │
//   START+2 = v ⎬ deva- — основа, целиком, не участвует в самом событии
//   START+3 = a │ (сдвигается на зазор и там сливается с au)
//   [START+4 — зазор: цель слияния, изначально пуст]
//   START+5 = au ⎭ окончание — равнозначный участник eka-ādeśa,
//                  сдвигается на тот же зазор, получает вриддхи
export const data = {
  initial: [
    { slot: START + 0, tr: 'd' },
    { slot: START + 1, tr: 'e' },
    { slot: START + 2, tr: 'v' },
    { slot: START + 3, tr: 'a' },
    { slot: START + 5, tr: 'au' },
  ],

  steps: [
    { kind: 'rule', ruleNum: 1, start: 2700, end: 14000, activeSlots: [START + 3, START + 4, START + 5], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Взаимное пульсирование — оба встречных influence с ОДИНАКОВЫМИ
    // параметрами (start/ringHoldDur) — синхронно, ни один не «главнее».
    { type: 'influence', from: START + 3, to: START + 5, start: 2700, ringHoldDur: 4000 },
    { type: 'influence', from: START + 5, to: START + 3, start: 2700, ringHoldDur: 4000 },

    // au сдвигается на зазор (слот 5) — дистанция 1.0 (половина исходных
    // 2), тот же старт/длительность, что и у слияния a ниже — оба
    // прибывают ОДНОВРЕМЕННО.
    { type: 'approach', movers: [START + 5], target: START + 4, start: 5300, approachDur: 900, distance: 1.0, retreat: false, pulse: false, jitterAmp: 0 },

    // a доезжает до au (merge) — au к этому моменту уже стоит на зазоре
    // (target.mesh.position.x читается динамически каждый кадр, поэтому a
    // «догоняет» реально движущуюся au, а не пустое место) — дистанция
    // тоже эффективно 1.0 слот, та же длительность. toGlyph:'au' — та же
    // буква, glyph не меняется здесь, замена случится позже, через
    // transform. label:'ekādeśa' — a равнозначный участник, не условие.
    { type: 'merge', from: START + 3, at: START + 5, toGlyph: 'au', start: 5300, dur: 900, label: 'ekādeśa' },

    // Вриддхи — начинается СРАЗУ по завершении слияния (5300+900=6200),
    // без своей паузы-осознания (anticipateDur:0 — вспышка merge уже
    // сыграла эту роль, вторая пауза подряд читалась бы как заминка, не
    // нарастание). atX — мировая позиция зазора (слот START+4, НЕ
    // slotX(START+5), куда указывает ключ au в cubes{}) — см. находку выше.
    { type: 'transform', at: START + 5, atX: slotX(START + 4), toGlyph: 'au', start: 6200, anticipateDur: 0, ...TRANSFORM_KIND.vrddhi, label: 'vṛddhi' },

    // au закрывает оставшийся зазор до v — СТРОГО после посадки transform
    // (t=1: 6200+4000=10200, anticipateDur:0 убрал 900мс из формулы) и
    // после signalHoldDur (цвет уже вернулся в истинный, 10200+500=10700)
    // — даёт зрителю увидеть готовый результат, прежде чем он тронется с
    // места. fromX — au ФИЗИЧЕСКИ уже на зазоре (не на своём slotX(at)) —
    // тот же найденный конфликт, что и у transform, только для approach
    // (baseXs иначе вычислялся бы от slotX(START+5), откуда au давно
    // уехала). distance:1.0 — от зазора (слот 5) до места a (слот 4).
    { type: 'approach', movers: [START + 5], target: START + 3, fromX: [slotX(START + 4)], start: 10700, approachDur: 1000, distance: 1.0, retreat: false, pulse: false, jitterAmp: 0 },

    // settle не прописан — считается автоматически.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
