// deva- «бог» + au (окончание du. N.Acc.V.) → devau «(оба) бога» —
// правило 1 на слот-движке.
//
// Правило проверено по Уитни/Панини (прямой запрос пользователя, не
// удовлетворилась формулировкой emeno «a поглощается»): Whitney §127 даёт
// ЕДИНУЮ таблицу комбинаций (a+i→e, a+u→o, a+e/ai→ai, a+o/au→au) — a+au
// обрабатывается ТОЙ ЖЕ операцией, что и обычная гуна/вриддхи, не отдельным
// «поглощением». Pāṇini 6.1.88 vṛddhir eci — технический термин eka-ādeśa
// («единая замена»): a и au ВМЕСТЕ заменяются одним результатом (который
// у этой пары просто совпадает по написанию с au — au уже предельная,
// вриддхи-ступень ряда u/o/au, заменять выше некуда). Источник и
// собранное значение полностью совпадают.
//
// МЕХАНИКА (прямая правка пользователя — a и au РАВНОЗНАЧНЫЕ участники,
// не «триггер влияет на жертву»; ГРАНИЦА показана зазором, как обычная
// морфологическая связка, а не сразу собранной):
//   0) a и au падают РАЗДЕЛЁННЫМИ зазором (та же логика, что и у внешнего
//      сандхи — граница ДО события не схлопнута).
//   1) a и au пульсируют ВМЕСТЕ, равнозначно — два встречных `influence`
//      (a→au И au→a), не один в одну сторону.
//   2) ОДНОВРЕМЕННО (не по очереди): a улетает вниз в отстойник (`elide`,
//      драматичный — это и есть всё содержание правила, не побочный
//      эффект) — И au начинает придвигаться, закрывая СРАЗУ и зазор, и
//      место a (`approach`, distance:2, старт РОВНО в тот же момент, что
//      и elide, не после его завершения).
//   3) a внизу рассыпается искрами (уже готовое поведение драматичного
//      elide — ничего дополнительно строить не нужно).
import { mountSlotExample, centeredStart } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 4-буквенному слову «devau» (тот же
// приём, что и у rule42 — финальное состояние держит внимание зрителя
// дольше всего, на нём и стоит фокусировать центр): centeredStart(4)=3.
// au падает ОТДЕЛЬНО, через зазор (слот 7 пуст изначально), не вплотную —
// прямая правка пользователя.
const START = centeredStart(4); // = 3
//   START+0 = d ⎫
//   START+1 = e │
//   START+2 = v ⎬ deva- — основа, целиком, не участвует в самом событии
//   START+3 = a │ (исчезает; сюда же придвинется au)
//   [START+4 — зазор: a и au падают раздельно]
//   START+5 = au ⎭ (окончание — равнозначный участник, не меняется,
//                   только сдвигается на место a)
export const data = {
  initial: [
    { slot: START + 0, tr: 'd' },
    { slot: START + 1, tr: 'e' },
    { slot: START + 2, tr: 'v' },
    { slot: START + 3, tr: 'a' },
    { slot: START + 5, tr: 'au' },
  ],

  steps: [
    { kind: 'rule', ruleNum: 1, start: 2700, end: 8800, activeSlots: [START + 3, START + 4, START + 5], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Взаимное пульсирование — оба встречных influence стартуют вместе,
    // ни один не «главнее» другого.
    { type: 'influence', from: START + 3, to: START + 5, start: 2700, ringHoldDur: 2200 },
    { type: 'influence', from: START + 5, to: START + 3, start: 2700, ringHoldDur: 2200 },

    // a улетает вниз — тот же holdOffset, что уже в rule42/50/55 (влево и
    // вниз). Драматичный (не quiet) — исчезновение a это и есть всё
    // содержание правила. label НЕ прописан — термин "lopa" под вопросом
    // именно для этого случая (пользователь не уверена), решено убрать
    // подпись совсем, а не показывать непроверенный термин.
    { type: 'elide', at: START + 3, start: 4900, holdOffset: { x: -0.45, y: -2.2, z: -0.4 } },

    // au придвигается на место a — закрывает СРАЗУ зазор (слот +4) и место
    // a (слот +3), distance:2 (не 1, т.к. au падала отдельно). Старт РОВНО
    // тот же момент, что и elide (не после), читается как одно взаимное
    // движение, не цепочка.
    { type: 'approach', movers: [START + 5], target: START + 3, start: 4900, approachDur: 1200, distance: 2.0, retreat: false, pulse: false, jitterAmp: 0 },

    // settle не прописан — считается автоматически.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
