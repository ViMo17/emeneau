// deva- «бог» (тематическая основа муж. рода) + au (окончание им./вин./
// зват. падежа двойственного числа) → devau «(оба) бога» — правило 1 на
// слот-движке.
//
// Источник (Whitney §127, Pāṇini 6.1.88 vṛddhir eci): единая таблица
// комбинаций a+простой гласный→гуна (правило 2) / a+дифтонг→вриддхи
// (правило 1). Обе строки — ОДНА и та же операция Pāṇini (адхикара 6.1.84
// ekaḥ pūrvaparayoḥ, «один [звук заменяет] предыдущий и последующий») —
// РАЗЛИЧИЕ только в том, КАКАЯ ступень применяется к правому гласному:
// гуна к простому, вриддхи к дифтонгу. Для пары a+au результат вриддхи
// СОВПАДАЕТ по написанию с au (au — уже сама предельная, вриддхи-ступень
// ряда u/o/au, повышать больше некуда) — но ОПЕРАЦИЯ применяется та же
// самая, просто с вырожденным (незаметным на глифе) результатом.
//
// РЕШЕНО (прямой запрос пользователя): раз мы УЧИМ правилу «a + дифтонг →
// вриддхи дифтонга», ученик должен увидеть, что вриддхи ПРИМЕНЯЕТСЯ к au,
// а не просто наблюдать, как au сдвигается на освободившееся место без
// видимого действия над ним. Поэтому au получает полноценный `transform`
// с вриддхи-сигналом (золото, двойной оборот — TRANSFORM_KIND.vrddhi),
// хотя `toGlyph` остаётся тем же 'au' — сам оборот+золото и есть
// визуализация «вриддхи была применена», глиф просто не меняется у ЭТОЙ
// конкретной пары. label:'vṛddhi' — та же терминология, что и у rule42.
//
// a при этом не «условие, которое просто исчезает» — она РАВНОЗНАЧНЫЙ
// участник eka-ādeśa (обе стороны вместе заменяются одним результатом,
// см. Pāṇini 6.1.84 выше): a поглощается ВНУТРИ того же акта, что
// производит вриддхи au. label:'ekādeśa' на elide (не 'lopa' — lopa,
// P. 1.1.60 adarśanaṃ lopaḥ, означает замену на НОЛЬ; здесь видимый
// результат есть).
//
// МЕХАНИКА:
//   0) a и au падают РАЗДЕЛЁННЫМИ зазором (морфологическая граница до
//      события не схлопнута).
//   1) a и au пульсируют ВМЕСТЕ, равнозначно — два встречных `influence`.
//   2) au оборачивается на месте (`transform`, вриддхи-сигнал, глиф не
//      меняется) — ОДНОВРЕМЕННО a уходит вниз в отстойник (`elide`,
//      драматичный, искры собственного цвета). НЕ approach — `transform`
//      каждый кадр во время активной фазы вращения пишет position.x
//      кубика заново (боковое раскачивание вокруг СВОЕГО слота), поэтому
//      одновременный approach того же кубика был бы перетёрт (см. тот же
//      найденный конфликт, что и в rule2).
//   3) ТОЛЬКО ПОСЛЕ того как au «приземлился» (оборот завершён, движок
//      больше не трогает его position.x) — au отдельным `approach`
//      закрывает зазор и занимает место a.
import { mountSlotExample, centeredStart, TRANSFORM_KIND } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 4-буквенному слову «devau»:
// centeredStart(4)=3. au падает ОТДЕЛЬНО, через зазор, не вплотную.
const START = centeredStart(4); // = 3
//   START+0 = d ⎫
//   START+1 = e │
//   START+2 = v ⎬ deva- — основа, целиком, не участвует в самом событии
//   START+3 = a │ (поглощается; сюда же придвинется au)
//   [START+4 — зазор: a и au падают раздельно]
//   START+5 = au ⎭ окончание — равнозначный участник eka-ādeśa,
//                  получает вриддхи-оборот, глиф не меняется
export const data = {
  initial: [
    { slot: START + 0, tr: 'd' },
    { slot: START + 1, tr: 'e' },
    { slot: START + 2, tr: 'v' },
    { slot: START + 3, tr: 'a' },
    { slot: START + 5, tr: 'au' },
  ],

  steps: [
    { kind: 'rule', ruleNum: 1, start: 2700, end: 11500, activeSlots: [START + 3, START + 4, START + 5], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Взаимное пульсирование — оба встречных influence стартуют вместе.
    { type: 'influence', from: START + 3, to: START + 5, start: 2700, ringHoldDur: 4000 },
    { type: 'influence', from: START + 5, to: START + 3, start: 2700, ringHoldDur: 4000 },

    // au — вриддхи НА МЕСТЕ (глиф тот же, сигнал+двойной оборот видимы).
    // Тот же разрыв (2600мс) между influence.start и transform.start, что
    // и в agnayas/rule2 — даёт зрителю время увидеть пульсацию до реакции.
    { type: 'transform', at: START + 5, toGlyph: 'au', start: 5300, ...TRANSFORM_KIND.vrddhi, label: 'vṛddhi' },

    // a поглощается — драматичный elide, это и есть содержание правила.
    { type: 'elide', at: START + 3, start: 6500, holdOffset: { x: -0.45, y: -2.2, z: -0.4 }, label: 'ekādeśa' },

    // au закрывает зазор — СТРОГО после посадки transform (t=1,
    // 5300+900+4000=10200, spinTurns:2 даёт вдвое более долгий оборот,
    // чем гуна).
    { type: 'approach', movers: [START + 5], target: START + 3, start: 10300, approachDur: 1200, distance: 2.0, retreat: false, pulse: false, jitterAmp: 0 },

    // settle не прописан — считается автоматически.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
