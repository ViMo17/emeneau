// deva- «бог» + au (окончание du. N.Acc.V.) → devau «(оба) бога» —
// правило 1 на слот-движке.
//
// Правило по источнику (data.js, emeno): «a перед дифтонгом au само
// поглощается им — дифтонг остаётся собой (потолок вриддхи, выше
// поднимать уже некуда). a — просто условие, само исчезает, не даёт
// результату ничего нового».
//
// МЕХАНИКА (прямая правка пользователя — a и au РАВНОЗНАЧНЫЕ участники,
// не «триггер влияет на жертву»):
//   1) a и au пульсируют ВМЕСТЕ, равнозначно — два встречных `influence`
//      (a→au И au→a), не один в одну сторону.
//   2) ОДНОВРЕМЕННО (не по очереди): a улетает вниз в отстойник (`elide`,
//      драматичный — это и есть всё содержание правила, не побочный
//      эффект) — И au начинает придвигаться на освободившееся место
//      (`approach`, старт РОВНО в тот же момент, что и elide, не после
//      его завершения).
//   3) a внизу рассыпается искрами (уже готовое поведение драматичного
//      elide — ничего дополнительно строить не нужно).
import { mountSlotExample } from '../lib/slot-engine.js';

//   0 = d ⎫
//   1 = e │
//   2 = v ⎬ deva- — основа, целиком, не участвует в самом событии
//   3 = a │ (исчезает)
//   4 = au ⎭ (окончание — равнозначный участник, не меняется, только
//            сдвигается на место a)
export const data = {
  initial: [
    { slot: 0, tr: 'd' },
    { slot: 1, tr: 'e' },
    { slot: 2, tr: 'v' },
    { slot: 3, tr: 'a' },
    { slot: 4, tr: 'au' },
  ],

  steps: [
    { kind: 'rule', ruleNum: 1, start: 2700, end: 8800, activeSlots: [3, 4], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Взаимное пульсирование — оба встречных influence стартуют вместе,
    // ни один не «главнее» другого.
    { type: 'influence', from: 3, to: 4, start: 2700, ringHoldDur: 2200 },
    { type: 'influence', from: 4, to: 3, start: 2700, ringHoldDur: 2200 },

    // a улетает вниз — тот же holdOffset, что уже в rule42/50/55 (влево и
    // вниз). Драматичный (не quiet) — исчезновение a это и есть всё
    // содержание правила.
    // label:'lopa' — ПОД ВОПРОСОМ именно для этого случая (пользователь
    // не уверена, термин уже подтверждён для śādhi/rule42/rule55, но
    // подходит ли он для «a поглощается потолком вриддхи» конкретно —
    // требует отдельной проверки по источнику, не решено).
    { type: 'elide', at: 3, start: 4900, holdOffset: { x: -0.45, y: -2.2, z: -0.4 }, label: 'lopa' },

    // au придвигается на место a — старт РОВНО тот же момент, что и elide
    // (не после), читается как одно взаимное движение, не цепочка.
    { type: 'approach', movers: [4], target: 3, start: 4900, approachDur: 1200, distance: 1.0, retreat: false, pulse: false, jitterAmp: 0 },

    // settle не прописан — считается автоматически.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
