// gach- + -ati → gacchati «он идёт» (правило 10) — ОДИН шаг геминации,
// ПОЛНОЕ СООТВЕТСТВИЕ ЭМЕНÓ (решение пользователя 2026-10-13, вариант А).
//
// РАЗБОР ФОРМЫ. gam- «идти» → наст. основа gach- — грамматический факт, не
// сандхи (Pāṇini 7.3.77 iṣu-gami-yamāṃ chaḥ), упоминается только в прозе.
// Правило 10 берёт основу gach- готовой (как у Эменó, с. 21).
//
// ПРАВИЛО 10 (Эменó, с. 21, дословно): «В положении после гласной ch
// заменяется на cch (W 227), т.е. ch количественно эквивалентна сочетанию
// согласных». Одна операция. Whitney §227 — то же; первая половина cch
// непридыхательная по ОБЩЕЙ условности удвоения придыхательных (§154:
// «doubled by prefixing its own corresponding non-aspirate»), не отдельное
// событие. Прежняя версия (2026-09) разлагала это на два шага (ch→chch,
// затем «деаспирация» ch→c) — такого разложения нет ни в одном источнике,
// отменено. У Панини механизм иной (6.1.73 che ca: наращение tuk = t;
// 8.4.40 stoḥ ścunā ścuḥ: t→c) — он дан только в тексте пояснения (2D),
// 3D следует Эменó.
//
// УСЛОВИЕ — ТОЛЬКО ПРЕДШЕСТВУЮЩИЙ ГЛАСНЫЙ (по книге «после гласной»):
// один `influence` от корневого a; правый a (начало окончания) условием
// не является.
//
// МЕХАНИЗМ: готовый `bud` — ch остаётся на месте, клон отпочковывается
// влево в зарезервированный слот СРАЗУ с глифом 'c' (§154: приставляется
// непридыхательный). Ничего нового в движке.
import { mountSlotExample, centeredStart } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 7-тайловому результату «gacchati»
// (g-a-c-ch-a-t-i) — centeredStart(7)=1.
const START = centeredStart(7); // = 1
//   START+0 = g  ⎫
//   START+1 = a  │ gach- «идти» (наст. основа gam-, грамм. факт, не сандхи)
//   START+2 = ।  ⎬ (пусто — сюда отпочкуется клон 'c';
//   START+3 = ch ⎭  исходное ch остаётся справа)
//   START+4 = a  ⎫ ati — тематич. -a- + личное оконч. 3 sg. -ti
//   START+5 = t  ⎬
//   START+6 = i  ⎭
export const data = {
  initial: [
    { slot: START + 0, tr: 'g' },
    { slot: START + 1, tr: 'a' },
    { slot: START + 3, tr: 'ch' },
    { slot: START + 4, tr: 'a' },
    { slot: START + 5, tr: 't' },
    { slot: START + 6, tr: 'i' },
  ],

  steps: [
    // Единственный шаг «правило 10»: условие (пульс) + геминация. Кончается
    // РОВНО с завершением bud (5720+1200=6920).
    { kind: 'rule', ruleNum: 10, start: 3220, end: 6920, activeSlots: [START + 1, START + 3, START + 2], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Условие: ch стоит ПОСЛЕ гласного — пульс от корневого a к ch.
    // ringHoldDur:2500 — гаснет ровно к началу bud (3220+2500=5720).
    { type: 'influence', from: START + 1, to: START + 3, start: 3220, ringHoldDur: 2500 },

    // Геминация: ch остаётся на месте, клон рождается сразу как 'c'
    // (непридыхательный той же варги, §154) и едет влево в пустой слот.
    { type: 'bud', from: START + 3, to: START + 2, toGlyph: 'c', start: 5720, label: 'геминация' },

    // settle — автоматически от step.end (6920).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
