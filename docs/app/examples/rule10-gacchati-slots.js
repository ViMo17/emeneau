// gach- + ati → gacchati «идёт» (правило 10) — ПЕРВЫЙ реальный тест гэпа
// DOUBLE, где геминация СОВМЕЩЕНА с деаспирацией первой копии (в отличие
// от rule61, hasan+agacchat→hasannagacchat, где n удваивается БЕЗ такой
// сложности — n не придыхательный, копии идентичны). Закрывает CLAUDE.md
// Часть 6, гэп 2 (для ЭТОГО конкретного правила — правило 49, tava
// cchāyā, использует ту же готовую механику, что и здесь).
//
// РАЗБОР ФОРМЫ. gam- «идти» (корень) — наст. система этого корня
// исторически образует основу gaccha- (не «gam-a-», архаичное
// палатализованное образование, ср. лат. -sc- начинательных глаголов) —
// ЭТО ГРАММАТИЧЕСКИЙ ФАКТ, НЕ САНДХИ (та же категория, что han-→gh в
// правиле 16, budh-→bhot в правиле 31 — упоминается только в прозе,
// не анимируется). Само правило 10 берёт основу gach- уже ГОТОВОЙ (как
// и у Эменó: «gach- + ati → gacchati») и описывает только то, что
// происходит с её конечным ch при присоединении окончания -ati
// (тематический показатель -a- + личное окончание 3 sg. -ti).
//
// ПРАВИЛО 10 (Whitney §227, сверено дословно по Wikisource: «ch is not
// allowed by the grammarians to stand in that form after a vowel, but is
// to be doubled, becoming cch... According to Pāṇini, ch is doubled
// within a word after either a long or a short vowel»; Эменó формулирует
// то же самое проще — «между двух гласных»). Точный номер сутры Панини
// для ИМЕННО этого случая (ch после гласного, не в связи с r/h или
// редупликацией дезидератива) не найден при проверке (WebSearch,
// несколько заходов) — открытый пункт, тот же класс, что уже был у
// правила 5 (ṛ→ir/ur) — не гадать номер, честно оставить как есть.
//
// ДЕАСПИРАЦИЯ ПЕРВОЙ КОПИИ — ОДНО СОБЫТИЕ С ГЕМИНАЦИЕЙ, НЕ ДВА
// ПОСЛЕДОВАТЕЛЬНЫХ (важная находка при построении, снимает вопрос
// CLAUDE.md о «недостающем шаге „перемещение придыхания“» — он не нужен).
// Whitney §154 (сверено дословно): «if such a mute is to be doubled, it
// is doubled by PREFIXING its own corresponding non-aspirate» — то есть
// результат удвоения ch НЕПОСРЕДСТВЕННО «c + ch» (неприд.+прид.), не
// «ch + ch» с последующей отдельной деаспирацией первой из двух копий.
// Механика — ТА ЖЕ операция `bud`, что и в rule61 (зеркало merge:
// источник остаётся на месте и вспыхивает, клон появляется в его позиции
// и едет в свой слот), но с ОДНИМ отличием, которое движок уже безусловно
// поддерживал и просто не было использовано: `toGlyph` клона ('c') НЕ
// совпадает с глифом источника ('ch', остаётся неизменным на своём
// месте) — деаспирация уже «встроена» в то, каким рождается клон, ни
// одной новой строчки в движке не потребовалось.
//
// НАПРАВЛЕНИЕ — зеркально rule61: там клон ехал ВПРАВО (в зазор между
// словами), здесь клон должен встать СЛЕВА от источника (первая копия
// «c» предшествует второй «ch» в результате «cch»). `applyBud` работает
// с `slotX(from)`/`slotX(to)` через обычный lerp — направление знака
// разности роли не играет, никакой правки движка не нужно.
//
// ПРИЧИНА (Whitney/Эменó оба явно называют условие «между двух гласных») —
// ОБА фланкирующих гласных (корневой a перед ch, тематический a после)
// пульсируют К ch одновременно, `influence` с двумя источниками — та же
// формула, что уже дважды применена (rule50, rule61) для двух условий
// одной цели, рамка группы появляется автоматически (>=2 источника).
import { mountSlotExample, centeredStart } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 7-тайловому результату «gacchati»
// (g-a-c-ch-a-t-i) — centeredStart(7)=1.
const START = centeredStart(7); // = 1
//   START+0 = g  ⎫
//   START+1 = a  │ gach- «идти» (наст. основа gam-, грамм. факт, не сандхи)
//   START+2 = ।  ⎬ (пусто — сюда «отпочкуется» неприд. копия c)
//   START+3 = ch ⎭ (источник геминации, остаётся на месте)
//   START+4 = a  ⎫ ati — тематич. -a- + личное оконч. 3 sg. -ti
//   START+5 = t  ⎬
//   START+6 = i  ⎭
export const data = {
  initial: [
    { slot: START + 0, tr: 'g' },
    { slot: START + 1, tr: 'a' },
    { slot: START + 3, tr: 'ch' },
    { slot: START + 4, tr: 'a' },
    { slot: START + 5, tr: 't' },
    { slot: START + 6, tr: 'i' },
  ],

  // Единственный шаг — само правило 10. activeSlots — оба условия
  // (корневой и тематический a), сам источник (ch) и будущее место
  // клона (пока пусто).
  steps: [
    { kind: 'rule', ruleNum: 10, start: 3220, end: 6920, activeSlots: [START + 1, START + 3, START + 4, START + 2], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Оба условия влияют на ch РАЗОМ — та же формула двух источников
    // одной цели, что уже применена в rule50/rule61. ringHoldDur:2500 —
    // пульс гаснет РОВНО к моменту начала bud (3220+2500=5720), без
    // разрыва и без нахлёста, тот же ритм, что и в rule61.
    { type: 'influence', from: START + 1, to: START + 3, start: 3220, ringHoldDur: 2500 },
    { type: 'influence', from: START + 4, to: START + 3, start: 3220, ringHoldDur: 2500 },

    // Геминация+деаспирация одним актом: ch (источник) остаётся на месте
    // неизменным (вторая, придыхательная копия), клон 'c' (первая,
    // непридыхательная копия) рождается на позиции ch и едет ВЛЕВО, в
    // зарезервированный пустой слот перед ним. label:'геминация' — тот
    // же временный кириллический термин, что и у rule61 (реестр CLAUDE.md,
    // «Словарь уже применённых подписей» — устоявшийся санскритский
    // термин для ЭТОГО конкретного случая, отдельно от общего dvitva/
    // dvirvacana, не найден, открытый пункт). Готово на 5720+1200=6920.
    { type: 'bud', from: START + 3, to: START + 2, toGlyph: 'c', start: 5720, label: 'геминация' },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — совпадает с моментом завершения bud).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
