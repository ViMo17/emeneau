// gach- + ati → gacchati «идёт» (правило 10) — ПЕРВЫЙ реальный тест гэпа
// DOUBLE, где геминация СОВМЕЩЕНА с деаспирацией первой копии. Закрывает
// CLAUDE.md Часть 6, гэп 2 (для ЭТОГО конкретного правила — правило 49,
// tava cchāyā, использует ту же готовую механику).
//
// РАЗБОР ФОРМЫ. gam- «идти» (корень) — наст. система этого корня
// исторически образует основу gaccha- (не «gam-a-», архаичное
// палатализованное образование, ср. лат. -sc- начинательных глаголов) —
// ЭТО ГРАММАТИЧЕСКИЙ ФАКТ, НЕ САНДХИ (та же категория, что han-→gh в
// правиле 16, budh-→bhot в правиле 31 — упоминается только в прозе, не
// анимируется). Само правило 10 берёт основу gach- уже ГОТОВОЙ (как и у
// Эменó: «gach- + ati → gacchati») и описывает только то, что происходит
// с её конечным ch при присоединении окончания -ati (тематический
// показатель -a- + личное окончание 3 sg. -ti).
//
// ПРАВИЛО 10 (Whitney §227, сверено дословно по Wikisource: «ch is not
// allowed by the grammarians to stand in that form after a vowel, but is
// to be doubled, becoming cch... According to Pāṇini, ch is doubled
// within a word after either a long or a short vowel»; Эменó — та же
// суть проще, «между двух гласных»). Точный номер сутры Панини для
// ИМЕННО этого случая не найден при проверке (WebSearch, несколько
// заходов) — открытый пункт, тот же класс, что уже был у правила 5.
//
// ДВА ОТДЕЛЬНЫХ ВИДИМЫХ ШАГА, НЕ ОДИН (прямая правка пользователя после
// первой версии: «мы должны отделить деаспирацию — каждую итерацию мы
// показываем пользователю. Сначала удваиваем ch, потом на шаге 2 —
// h сползёт»). Whitney §154 формулирует итог как ОДИН акт («doubled by
// PREFIXING its own corresponding non-aspirate»), но педагогически
// разложен на ДВЕ итерации, той же логикой, что уже применена к правилу
// 9 («the last is dropped, AND AGAIN the last» — там тоже одна и та же
// сутра показана двумя отдельными шагами):
//  1. Геминация (`bud`, как в rule61) — ch отпочковывает клона С ТЕМ ЖЕ
//     глифом 'ch' (истинное удвоение без изменений) → «chch». Это НЕ
//     изобретённая промежуточная стадия — Whitney сам называет «chch»
//     реальным рукописным вариантом написания того же результата.
//  2. Деаспирация (`transform`) — ЛЕВАЯ (более ранняя) копия теряет
//     придыхание: ch→c. НАЙДЕНО при проектировании: c и ch — ПАРА ВНУТРИ
//     ОДНОЙ (палатальной) варги, отличаются РОВНО придыханием — это
//     буквально `TRANSFORM_KIND.vargaPair` («придых↔непридых» уже прямо
//     названо одним из её случаев в реестре, Часть 3) — ТА ЖЕ операция,
//     что у cartva/jaśtva, ни одной новой строчки в движке не потребовалось.
//     ПРАВАЯ (исходная) копия — она же физический источник bud — служит
//     причиной (`influence`): наличие идентичного соседа — вот почему
//     именно эта, более ранняя копия теряет придыхание.
// Термин пилюли для шага 2 — временный placeholder («деаспирация»,
// кириллицей): это НЕ cartva (та — про звонкость, ch/c — оба глухие,
// разница только в придыхании) и не отдельно найденный санскритский
// термин — открытый пункт, тот же класс, что «геминация» у rule61.
//
// ГЕОМЕТРИЯ ВРАЩЕНИЯ: после геминации у клона ОБА соседа заняты (корневой
// a слева, исходное ch справа, без единого зазора) — та же ситуация, что
// уже трижды встречалась (rule2/rule6/suhārt): `clearance:0`/
// `clearanceZ:-0.5`.
import { mountSlotExample, centeredStart, TRANSFORM_KIND } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 7-тайловому результату «gacchati»
// (g-a-c-ch-a-t-i) — centeredStart(7)=1.
const START = centeredStart(7); // = 1
//   START+0 = g  ⎫
//   START+1 = a  │ gach- «идти» (наст. основа gam-, грамм. факт, не сандхи)
//   START+2 = ।  ⎬ (пусто — сюда «отпочкуется» клон, сначала 'ch', потом
//   START+3 = ch ⎭  деаспирируется до 'c'; исходное ch остаётся справа)
//   START+4 = a  ⎫ ati — тематич. -a- + личное оконч. 3 sg. -ti
//   START+5 = t  ⎬
//   START+6 = i  ⎭
export const data = {
  initial: [
    { slot: START + 0, tr: 'g' },
    { slot: START + 1, tr: 'a' },
    { slot: START + 3, tr: 'ch' },
    { slot: START + 4, tr: 'a' },
    { slot: START + 5, tr: 't' },
    { slot: START + 6, tr: 'i' },
  ],

  steps: [
    // Шаг «правило 10», ПЕРВАЯ итерация: геминация (ch→chch). activeSlots
    // — оба условия (корневой и тематический a), источник (ch) и будущее
    // место клона (пока пусто).
    { kind: 'rule', ruleNum: 10, start: 3220, end: 7120, activeSlots: [START + 1, START + 3, START + 4, START + 2], color: 0xAFBFD4, primary: true },
    // Шаг «правило 10», ВТОРАЯ итерация: деаспирация левой копии
    // (ch→c). activeSlots — клон (превращается) и исходное ch (причина —
    // идентичный сосед).
    { kind: 'rule', ruleNum: 10, start: 7120, end: 13370, activeSlots: [START + 2, START + 3], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Оба условия влияют на ch РАЗОМ — та же формула двух источников
    // одной цели, что уже применена в rule50/rule61. ringHoldDur:2500 —
    // пульс гаснет РОВНО к моменту начала bud (3220+2500=5720), тот же
    // ритм, что и в rule61 (bud, в отличие от transform, уже проверен
    // безопасным на этой точной границе — не трогает cube.scale цели тем
    // же способом, что и pulse влияния).
    { type: 'influence', from: START + 1, to: START + 3, start: 3220, ringHoldDur: 2500 },
    { type: 'influence', from: START + 4, to: START + 3, start: 3220, ringHoldDur: 2500 },

    // Геминация: ch (источник) остаётся на месте неизменным, клон
    // рождается С ТЕМ ЖЕ глифом 'ch' (истинное удвоение, «chch») и едет
    // ВЛЕВО в зарезервированный пустой слот. Готово на 5720+1200=6920.
    { type: 'bud', from: START + 3, to: START + 2, toGlyph: 'ch', start: 5720, label: 'геминация' },

    // ПРИЧИНА второй итерации: исходное ch (теперь физический сосед
    // клона) пульсирует К клону — «наличие идентичной копии рядом» это и
    // есть условие деаспирации. 200мс буфер после того, как bud реально
    // завершился (6920+200=7120). ringHoldDur:2600 — СТРОГО больше dur
    // цели по умолчанию (2500) — тот же запас, что уже требуется перед
    // ЛЮБЫМ transform на этом же кубике (rule2/suhārt: конфликт за
    // cube.scale между остаточным pulse влияния и paus-осознание
    // transform'а, если начать точно на границе, без запаса).
    { type: 'influence', from: START + 3, to: START + 2, start: 7120, ringHoldDur: 2600 },

    // Деаспирация: левая копия (клон) теряет придыхание — ch→c. Пара
    // внутри одной (палатальной) варги, придых↔непридых — ТА ЖЕ операция,
    // что cartva/jaśtva. clearance:0/clearanceZ:-0.5 — оба соседа (a
    // слева, ch справа) заняты без единого зазора. Пауза чистой
    // пульсации перед реакцией — 2600мс (7120+2600=9720).
    { type: 'transform', at: START + 2, toGlyph: 'c', start: 9720, ...TRANSFORM_KIND.vargaPair, clearance: 0, clearanceZ: -0.5, label: 'деаспирация' },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — совпадает с моментом завершения transform,
    // 9720+900(anticipateDur)+1800(dur,vargaPair)+250(signalHoldDur)+
    // 700(holdDur)=13370).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
