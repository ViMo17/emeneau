// acchid- + vṛddhi + s + ta → acchaitta «вы (мн.ч.) рассекли» (правило 12) —
// s между двух смычных → 0.
//
// РАЗБОР ФОРМЫ. chid- «рассекать, раскалывать» (корень VII класса,
// конечный согласный — дентальный d) + augment a- (маркер прошедшего
// времени, здесь — аориста) + сигматический показатель аориста -s- (siC)
// + личное окончание 2 л. мн.ч. действ. залога (вторичный ряд, аористно-
// имперфектный) -ta. «acchid-» дан УЖЕ готовым (a+ch удвоено до «cch» —
// ch не может стоять после гласного внутри слова без удвоения, Whitney
// §227 — ТА ЖЕ формула, что уже построена в правиле 10, повторно
// проигрывать её здесь незачем, geminate-состояние взято как исходные
// данные, тот же приём, что и у rule10 с готовой основой «gach-»).
//
// ПРАВИЛО 12 (Whitney §233e, цитируется в §882–883 — прямая парадигма
// корня chid: «ácchāitsam» (1 sg.), «ácchāittam, ácchāittām, ácchāitta»
// (2 дв./3 дв./2 мн.) — «the omission of s in the active persons... is a
// case of very rare occurrence»). Pāṇini 8.2.26 झलो झिल jhalo jhali
// (анувритти sasya от 8.2.24, lopaḥ от 8.2.23 — «[deletion of] s after a
// root ending in a stop consonant and before an ending beginning with a
// stop consonant», сверено по независимому источнику — конспект «The
// Sanskrit Aorist», Columbia University, с самим текстом сутры на
// деванагари, не только резюме). «Jhal» — все смычные (звонкие и глухие)
// + свистящие + h, БЕЗ носовых/полугласных — оба фланга (t слева, t
// справа) входят в этот класс.
//
// НАЙДЕННАЯ ОШИБКА В РАНЕЕ ЗАПИСАННОМ ПРИМЕРЕ (interaction-registry.md):
// прежняя запись «acchid- + s-ta → acchitta» (без вриддхи) не находит
// подтверждения ни в одном источнике — единственная реально засвиде-
// тельствованная форма для chid — «acchaitta» (с вриддхи i→ai, Pāṇini
// 7.2.1 सिचि वृद्धिः परस्मैपदेषु sici vṛddhiḥ parasmaipadeṣu, «vṛddhi of a
// root before the suffix siC and before parasmaipada endings» — тот же
// независимый источник). Найдена и структурная параллель на ДРУГОМ корне
// (vas- «жить», активный аорист: avāttam/avātta — конечный смычный
// основы + пропавшее s + начальное t окончания → поверхностное «tt») —
// подтверждает, что механизм «смычный+пропавшее s+смычный→удвоенный
// смычный» регулярный, не изобретён специально под chid.
//
// ГЛАВНЫЙ ПРИНЦИП (CLAUDE.md, Часть 2) — ДВАЖДЫ ИСПРАВЛЕНО ПОСЛЕ ПРЯМОЙ
// ПРАВКИ ПОЛЬЗОВАТЕЛЯ. Первый заход ронял все 8 фонем ОДНИМ сплошным
// рядом без единого зазора. Второй заход развёл корень от «-s-+-ta»
// одним зазором, но склеил показатель аориста -s- с личным окончанием
// -ta в ОДИН неразделимый блок — прямая правка пользователя («мы
// продумывали ранее подчеркивать единую грамм. основу — не корректно ли
// будет разделить их пробелом?»): -s- (siC, стемообразующий показатель)
// и -ta (личное окончание) — ДВА разных морфа, даже если синтетическая
// форма выглядит слитно, и должны падать РАЗДЕЛЁННЫМИ, как и любая
// другая граница. Исправлено — ТРИ физических блока с зазором между
// каждой парой соседних:
//  (1) корень+augment «acchid-» (a,c,ch,i,d) — НЕПОДВИЖНЫЙ якорь, как
//      śās в śādhi/agni в agnayas;
//  (2) показатель аориста -s- (одна буква) — падает и движется САМ;
//  (3) личное окончание -ta (t,a) — падает и движется САМ, ПОСЛЕ (2).
// (2) подъезжает к (1) первым (`approach`, зазор закрывается) — это
// прибытие И ЕСТЬ причина вриддхи (Pāṇini 7.2.1, s ещё не физически
