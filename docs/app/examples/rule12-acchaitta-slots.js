//     (TRANSFORM_KIND.vargaPair, 180°, Pāṇini 8.4.55 khari ca).
//  B5 [Правило 12] — само s, оказавшееся между двумя смычными, исчезает
//     без остатка — обычный полный (не quiet) `elide`, label:'lopa' —
//     то же явление, что уже показано на śādhi/rule55/suhārt/rule9.
// Реакция (лопа) происходит РОВНО в паузе двухотрезочного approach
