// лопы (s зажато между t слева от cartva и t справа от подъехавшего
// окончания); в паузе — реакция (лопа); второй отрезок довозит
// окончание НА ОСВОБОДИВШЕЕСЯ место s (два t становятся геометрически
// смежными — прямой смысл правила 12).
//
// ТРИ СОБЫТИЯ ЦЕПОЧКОЙ, НИ ОДНОГО НОВОГО В ДВИЖКЕ (все три уже построены
// на других правилах):
