// слова śāsdhi, показывая исчезновение s как событие само по себе. Ошибка
// та же, что уже была с āsīt: суть примера — во взаимодействии частей,
// не в готовом целом. Теперь ŚĀS (корень) и DHI (окончание) падают
// РАЗДЕЛЁННО, через зазор, и само исчезновение s — СЛЕДСТВИЕ того, что DH
// приближается и вступает в контакт, а не независимое событие на статичном
// слове. См. общий принцип в algoritm-agnayas-shablon.md.
import { mountSlotExample, slotX } from '../lib/slot-engine.js';

// śās- «править, повелевать, учить» + -dhi (окончание 2 л. ед.ч.
// повелительного накл., «сильная» атематическая форма) → śādhi.
// Подтверждено независимо: learnsanskrit.org, «Internal Consonant Sandhi»
// — тот же самый пример (śās + dhi → śādhi).
//   3 = ś  ⎫
//   4 = ā  ⎬ корень śās- — неподвижный якорь, как AS в āsīt
//   5 = s  ⎭ (сольётся/исчезнет — реакция на приближение DH)
//   [6 — зазор: DHI ещё отдельная морфологическая единица]
//   7 = dh ⎫ окончание -dhi — падает ОТДЕЛЬНО, через зазор
//   8 = i  ⎭ (i едет вместе с dh, как один блок)
