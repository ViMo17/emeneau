    //      по прямой просьбе «я бы её увеличила») — контакт установлен,
    //      ничего не двигается; ИМЕННО в этом окне срабатывает elide
    //      ниже, теперь заметно более длинный (таянию нужно время);
    //   3) DH+I довершают путь (leg2Dur) — въезжают на уже свободное
