// śādhi (правило 15) на слот-движке — первый пример на операцию elide
// (буква исчезает без замены). По образцу rule3-agnayas-slots.js /
// rule7-asit.js — data + mount(), один источник для теста и приложения.
import { mountSlotExample, slotX } from '../lib/slot-engine.js';

// śās- «править, повелевать, учить» + -dhi (окончание 2 л. ед.ч.
// повелительного накл., «сильная» атематическая форма) → śādhi.
// Подтверждено независимо: learnsanskrit.org, «Internal Consonant Sandhi»
// — тот же самый пример (śās + dhi → śādhi).
// Слоты — ВСЕ пять подряд, без зазоров (это одно слитное слово с самого
// начала, не два морфологических блока с паузой между ними, как в āsīt):
//   3 = ś
//   4 = ā
//   5 = s — исчезает (elide), ничего не появляется взамен
//   6 = dh — после исчезновения s подъедет на позицию слота 5
//   7 = i — после исчезновения s подъедет на позицию слота 6
// Раскладка подобрана так, чтобы центрировался ИТОГ (4 буквы, слоты
// 3,4,5,6 по факту финальных позиций), а не старт (5 букв) — тот же
// урок, что уже был с āsīt (заход 15/19).
export const data = {
  initial: [
    { slot: 3, tr: 'ś' },
    { slot: 4, tr: 'ā' },
    { slot: 5, tr: 's' },
    { slot: 6, tr: 'dh' },
    { slot: 7, tr: 'i' },
  ],

  // Единственный шаг — сама сандхи, без предварительной грамматики (в
  // отличие от agnayas/āsīt): корень и окончание уже в нужной форме,
  // ничего грамматически не готовится заранее. activeSlots — s и dh,
  // буквы в непосредственном фонетическом контакте (правило записано
  // именно как s+dh→∅); ś, ā, i — контекст, притенены как фон.
  steps: [
    // color: 0x9FB4D2 — тот же hex, что у .c2 в sanskrit-sandhi-app.html
    // (тир правила 15, g:'c2' в массиве RULES).
    { kind: 'rule', ruleNum: 15, start: 2600, end: 4250, activeSlots: [5, 6], color: 0x9FB4D2, primary: true },
  ],

  ops: [
    // s исчезает без замены — растворяется (масштаб+прозрачность к 0),
    // мягкое кольцо-«всплеск» ровно в момент полного исчезновения.
    { type: 'elide', at: 5, start: 2600, dur: 700 },

    // dh и i закрывают образовавшийся промежуток — сразу же, без паузы
    // (прямое следствие исчезновения s, не отдельное событие). target:4
    // (ā) используется ТОЛЬКО для направления сдвига (существующий
    // сосед) — сам s к этому моменту уже исчез, ссылаться на него нельзя.
    {
      type: 'approach', movers: [6, 7], target: 4, start: 3300,
      approachDur: 800, holdDur: 0, retreat: false,
      distance: 1.0, jitterAmp: 0, pulse: false,
    },

    // settle не прописан — считается автоматически (см. заход 8):
    // 1с после того, как последняя буква вернёт истинный цвет.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
