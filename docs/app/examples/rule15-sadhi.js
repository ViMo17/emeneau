// śādhi (правило 15) на слот-движке — операция elide (буква исчезает без
// замены). ŚĀS (корень) и DHI (окончание) падают РАЗДЕЛЁННО, через зазор,
// и само исчезновение s — СЛЕДСТВИЕ того, что DH приближается и вступает
// в контакт, а не независимое событие на статичном слове (не готовое
// слово śāsdhi с исчезновением s как событием сами по себе — см. главный
// методологический принцип в CLAUDE.md, Часть 2).
import { mountSlotExample } from '../lib/slot-engine.js';

// śās- «править, повелевать, учить» + -dhi (окончание 2 л. ед.ч.
// повелительного накл., «сильная» атематическая форма) → śādhi.
// Подтверждено независимо: learnsanskrit.org, «Internal Consonant Sandhi»
// — тот же самый пример (śās + dhi → śādhi).
//   3 = ś  ⎫
//   4 = ā  ⎬ корень śās- — неподвижный якорь, как AS в āsīt
//   5 = s  ⎭ (сольётся/исчезнет — реакция на приближение DH)
//   [6 — зазор: DHI ещё отдельная морфологическая единица]
//   7 = dh ⎫ окончание -dhi — падает ОТДЕЛЬНО, через зазор
//   8 = i  ⎭ (i едет вместе с dh, как один блок)
// ВРЕМЕННЫЙ ЭКСПЕРИМЕНТ (диагностика асимметрии прозрачности, CLAUDE.md
// Часть 6 п.0): все номера слотов сдвинуты влево на 3 (0,1,2,4,5 вместо
// 3,4,5,7,8) по прямой просьбе пользователя — проверить гипотезу, что
// прозрачность притенённых кубиков работает только до определённого
// номера слота/координаты X, независимо от того, что показывает пример.
// Промежутки между буквами и все ссылки в ops/steps ниже сдвинуты
// СИНХРОННО — семантика примера не меняется, меняется только позиция
// целиком. Вернуть исходные номера (3,4,5,7,8) после проверки гипотезы.
export const data = {
  initial: [
    { slot: 0, tr: 'ś' },
    { slot: 1, tr: 'ā' },
    { slot: 2, tr: 's' },
    { slot: 4, tr: 'dh' },
    { slot: 5, tr: 'i' },
  ],

  // Единственный шаг — сама сандхи, без предварительной грамматики (в
  // отличие от agnayas/āsīt): корень и окончание уже в нужной форме.
  // activeSlots — s и dh, буквы в непосредственном фонетическом контакте
  // (правило записано как s+dh→∅); ś, ā, i — контекст, притенены как фон.
  steps: [
    // color — 0x869EC1, должен ТОЧНО совпадать с реальным CSS-цветом тира
    // .c2 в sanskrit-sandhi-app.html (agnayas сверен так же точно, 0xAFBFD4
    // == .c1) — иначе цвет чипа шага и цвет карточки правила расходятся.
    // end=7300 — elide (рождение+пауза+угасание, старт 3950, длительность
    // по умолчанию 1300+800+1100=3200) реально завершается в 7150; end
    // должен наступать НЕ РАНЬШЕ этого момента, иначе притенение
    // (activeSlots) и сама elide короткое время конфликтуют за opacity
    // одного и того же кубика (обе пишут в него каждый кадр).
    { kind: 'rule', ruleNum: 15, start: 2600, end: 7300, activeSlots: [2, 4], color: 0x869EC1, primary: true },
  ],

  ops: [
    // Три явные фазы (см. midDistance/midHoldDur/leg2Dur в applyApproach):
    // подъезд вплотную к S → пауза (в ней — реакция) → въезд на
    // освободившееся место. midHoldDur не обязан дожидаться ПОЛНОГО
    // угасания S (elide — погружение вниз, та же механика, что у split) —
    // достаточно, чтобы было заметно видно, как S уходит вниз, прежде чем
    // DH тронется. holdPulse — во время паузы DH пульсирует кольцом
    // (несколько раз подряд, не один разовый всплеск, иначе не видно
    // факта воздействия DH на S) — техника взята из старого файла
    // ассимиляции (docs/effects/rule-assimilation-v2-via-elements.html:
    // там триггер тоже пульсировал непрерывно, пока шло воздействие на
    // цель), только не текстурой на грани, а уже готовым spawnPulseRing.
    {
      type: 'approach', movers: [4, 5], target: 2, start: 2600,
      approachDur: 900, midDistance: 1.0, midHoldDur: 1400, leg2Dur: 600,
      distance: 2.0, retreat: false, jitterAmp: 0, pulse: false,
      holdPulse: true,
    },

    // РЕАКЦИЯ: S не тает на месте, а ПОГРУЖАЕТСЯ в отстойник вниз — та же
    // механика rise→hold→fade, что у split (E поднимается вверх), только
    // знак y отрицательный: направление смысловое — вверх означает
    // «превращается» (см. split), вниз — «пропадает без следа» (чистая
    // элизия). start НЕ должен совпадать с моментом пульса на DH — реакция
    // должна начинаться ПОСЛЕ того, как первая волна DH→S реально долетает
    // (leg1End=3500 + holdWaveTravel=400 + запас 50 = 3950), иначе выглядит
    // так, будто DH даёт импульс, а S его не получает — видна причинно-
    // следственная цепочка, не два независимых события по расписанию.
    { type: 'elide', at: 2, start: 3950 },

    // settle не прописан — считается автоматически: 1с после того, как
    // последняя буква вернёт истинный цвет.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
