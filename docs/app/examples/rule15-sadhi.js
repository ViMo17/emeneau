// śādhi (правило 15) на слот-движке — операция elide (буква исчезает без
// замены). ПЕРЕСОБРАНО (заход 28) — первая версия начинала с уже готового
// слова śāsdhi, показывая исчезновение s как событие само по себе. Ошибка
// та же, что уже была с āsīt: суть примера — во взаимодействии частей,
// не в готовом целом. Теперь ŚĀS (корень) и DHI (окончание) падают
// РАЗДЕЛЁННО, через зазор, и само исчезновение s — СЛЕДСТВИЕ того, что DH
// приближается и вступает в контакт, а не независимое событие на статичном
// слове. См. общий принцип в algoritm-agnayas-shablon.md.
import { mountSlotExample, slotX } from '../lib/slot-engine.js';

// śās- «править, повелевать, учить» + -dhi (окончание 2 л. ед.ч.
// повелительного накл., «сильная» атематическая форма) → śādhi.
// Подтверждено независимо: learnsanskrit.org, «Internal Consonant Sandhi»
// — тот же самый пример (śās + dhi → śādhi).
//   3 = ś  ⎫
//   4 = ā  ⎬ корень śās- — неподвижный якорь, как AS в āsīt
//   5 = s  ⎭ (сольётся/исчезнет — реакция на приближение DH)
//   [6 — зазор: DHI ещё отдельная морфологическая единица]
//   7 = dh ⎫ окончание -dhi — падает ОТДЕЛЬНО, через зазор
//   8 = i  ⎭ (i едет вместе с dh, как один блок)
export const data = {
  initial: [
    { slot: 3, tr: 'ś' },
    { slot: 4, tr: 'ā' },
    { slot: 5, tr: 's' },
    { slot: 7, tr: 'dh' },
    { slot: 8, tr: 'i' },
  ],

  // Единственный шаг — сама сандхи, без предварительной грамматики (в
  // отличие от agnayas/āsīt): корень и окончание уже в нужной форме.
  // activeSlots — s и dh, буквы в непосредственном фонетическом контакте
  // (правило записано как s+dh→∅); ś, ā, i — контекст, притенены как фон.
  steps: [
    // color: 0x9FB4D2 — тот же hex, что у .c2 в sanskrit-sandhi-app.html
    // (тир правила 15, g:'c2' в массиве RULES).
    { kind: 'rule', ruleNum: 15, start: 2600, end: 4150, activeSlots: [5, 7], color: 0x9FB4D2, primary: true },
  ],

  ops: [
    // DH+I приближаются к S через зазор — движение ПРИЧИНА, не декорация.
    // distance:2.0 — закрывает и зазор (1 слот), и позицию самого S (ещё
    // 1 слот): к моменту, когда DH визуально доедет до места S, S уже
    // исчезнет (см. elide ниже), и DH плавно займёт освободившееся место
    // без наложения. target:5 (S) — пока S ещё существует, направление
    // движения берётся от него.
    {
      type: 'approach', movers: [7, 8], target: 5, start: 2600,
      approachDur: 1400, holdDur: 0, retreat: false,
      distance: 2.0, jitterAmp: 0, pulse: false,
    },

    // РЕАКЦИЯ: S исчезает — не сразу, а когда DH уже заметно приблизился
    // (старт elide — на 600мс позже старта approach, т.е. когда DH прошёл
    // заметную часть пути) — читается как «приближение вызвало реакцию»,
    // не «S сам по себе растворился». Завершается за 300мс до конца
    // approach — DH приезжает уже на чистое место, без наложения.
    { type: 'elide', at: 5, start: 3200, dur: 500 },

    // settle не прописан — считается автоматически (см. заход 8):
    // 1с после того, как последняя буква вернёт истинный цвет.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
