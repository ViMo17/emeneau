// bhava- + -ī- + -t → bhavet «был бы» — правило 2 на слот-движке.
//
// РАЗБОР ФОРМЫ. bhū- «быть» — глагольный корень I класса (тематическое
// спряжение): основа настоящего времени образуется присоединением
// тематического гласного -a- к гунированному корню (bhū→bho, guṇa
// ряда ū/o/au) — bho+a→bhava- («bh-a-v-a», см. Whitney §734, §127 —
// вставка глайда v между гласными o и a, та же техника, что даёт devau
// в правиle 1). Оптатив (желательное наклонение, «был бы») строит свою
// форму от ЭТОЙ основы настоящего времени, не от голого корня. Личное
// окончание -t — показатель 3-го лица единственного числа действительного
// залога, то же самое окончание, что и в изъявительном наклонении
// (bhávati «есть» → 3 sg. -ti, в оптативе — просто -t, без -i).
//
// ИСТОЧНИК (Whitney §565a, проверено по первоисточнику дословно):
// показатель наклонения после ОСНОВЫ НА a — это безударный ī; «этот ī
// СЛИВАЕТСЯ с конечным a [основы] в e» («blends with the final a to
// e»). Итоговый набор личных окончаний оптатива для a-основ так и
// даётся ГОТОВЫМИ формами (eyam, es, et, etam...) — a и ī нигде не
// существуют как отдельные, соседствующие звуки, они заменяются ОДНИМ
// актом. Это Pāṇini 6.1.87 ād guṇaḥ — сосед по таблице 6.1.88 vṛddhir
// eci (см. правило 1: та же адхикара 6.1.84 ekaḥ pūrvaparayoḥ, «один
// [звук заменяет] предыдущий и последующий» — единый механизм eka-ādeśa,
// просто с разной ступенью результата: гуна здесь, вриддхи там).
//
// МЕХАНИКА (перенесена с правила 1, после подтверждения на нём — «мы же
// сливаем их»): a и ī — равнозначные участники eka-ādeśa, ОБА физически
// сдвигаются РОВНО НА ОДИН СЛОТ навстречу друг другу, на уже
// существующий зазор между ними, и там сливаются техникой `merge` (та
// же, что a+a→ā в rule7 и a+au→au в rule1): мувер (a) доезжает и
// исчезает точно на контакте, вспышка на выжившем (ī). t падает СЛИТНО с
// ī (между ними самими события нет — см. ниже) и сдвигается ВМЕСТЕ с ней
// уже на этом шаге, сохраняя смежность. Результат сразу серебряный —
// гуна начинается СРАЗУ по завершении merge, `anticipateDur:0` (своя
// пауза-осознание не нужна, вспышка merge её уже даёт).
//
// РАСКЛАДКА ГРУПП. Основа bhava- падает отдельно от суффикса-с-
// окончанием: сама формула («bhava- + -ī- + -t») выделяет основу как
// одну часть, а -ī-t как связанный комплекс личной формы, между которыми
// и происходит единственное значимое событие — граница внутри самого
// -ī-t (между показателем наклонения и личным окончанием) сандхи не
// знает, поэтому ī и t падают уже СЛИТНО, без зазора между собой.
//
// ДВА ШАГА (живая проверка пользователя: «Т исчезает и появляется
// только в самом конце» — с ОДНИМ шагом на весь таймлайн t была
// притенена от начала до самого settle, включая собственную финальную
// approach-фазу). Шаг 1 — сама гуна (a+ī→e), t НЕ участник, притенена.
// Шаг 2 — начинается РОВНО там же, где кончается первый (без зазора,
// stepRamp сам сглаживает переход) — t становится активной РОВНО когда
// начинает своё видимое движение (закрывающий approach), не раньше и не
// позже: «включается» вместе со своим собственным действием, а не ждёт
// общего settle в конце.
//
// clearanceZ у transform — ī и t стоят ВПЛОТНУЮ (без зазора): угловая
// точка вращающегося куба на диагональных углах (~45°/135°) физически
// дальше от центра (CUBE_SIZE·√2/2), чем его же грань в покое
// (CUBE_SIZE/2) — разница (~0.23) больше зазора между гранями соседних
// кубиков (SLOT-CUBE_SIZE=0.1), угол реально проходит СКВОЗЬ соседа без
// поправки. ЗНАК ИСПРАВЛЕН (живая проверка, скриншот): первая версия
// (+0.3, «на зрителя») сдвигала кубик БЛИЖЕ к камере (camera.z=9.5>0) —
// в перспективной проекции это делает его КРУПНЕЕ на экране, только
// усиливая визуальное перекрытие с соседом, а не снимая его («мешаются
// текстуры Е и Т» — оказалось хуже, не лучше). Верное направление — ОТ
// камеры (отрицательный знак): кубик визуально МЕНЬШЕ на пике вращения,
// меньше шанс перекрыть соседа, при этом 3D-разведение по глубине то же
// самое. Также увеличена амплитуда (0.5, было 0.3) — щедрый запас, не
// точный подбор (первая попытка уже расходилась с реальностью).
//
// ringRgb у обоих influence — ОБЩИЙ (не свой фонетический цвет у каждой
// стороны): a и ī равнозначны, задача — читаться как ОДНО согласованное
// дыхание, не как два разноцветных, пусть даже идеально синхронных по
// времени (тайминг и без того один и тот же elapsed на кадр — расхождение
// было визуальным, не числовым: живая проверка «не синхронизированы
