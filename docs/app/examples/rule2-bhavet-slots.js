// bhava- «быть» (тематическая основа наст. вр., класс I, от bhū-) +
// -ī- (суффикс оптатива) + -t (личное окончание 3 л. ед. ч. действ.
// залога) → bhavet «был бы» — правило 2 на слот-движке.
//
// Источник (Whitney §127, та же таблица, что и rule1 — там «потолок»
// вриддхи, здесь гуна): a + простой гласный (кроме a/ā) → гуна этого
// гласного. Уже проверено в Фазе 2 (см. существующий EXAMPLES[2].
// roleDemo.text, data.js): «a — только условие сдвига, сам ничего не
// отдаёт» — Whitney §338a, ТА ЖЕ категория, что и гунация i→e в agnayas
// (окончание/суффикс требует гунации соседнего гласного — грамматика,
// не отдельная сандхи-операция, не eka-ādeśa rule1). Механика — влияние
// + transform на месте, ТОТ ЖЕ приём, что у agnayas, не eka-ādeśa-
// техника rule1/rule50.
//
// МЕХАНИКА (прямая правка пользователя — части даны в формуле ОТДЕЛЬНО
// через «+», значит падают ОТДЕЛЬНО, каждая со своим зазором; порядок —
// сначала гунация, потом отдельным шагом придвигается t):
//   0) Три группы падают РАЗДЕЛЁННЫМИ: bhava- (bh,a,v,a) — суффикс ī —
//      окончание t. Два зазора.
//   1) Гунация — ТОЛЬКО НА МЕСТЕ, без физического сближения (тот же
//      приём, что у agnayas: influence через зазор + transform в своём
//      слоте). a уходит вниз тихо (elide, quiet — условие, не
//      содержание правила), ī оборачивается в e (transform, дефолтная
//      гуна, label:'guṇa').
//      РЕАЛЬНЫЙ НАЙДЕННЫЙ БАГ на этапе планирования (численная
//      симуляция): `applyTransform` КАЖДЫЙ кадр во время активного
//      вращения принудительно пишет `position.x = slotX(op.at)` (боковое
//      раскачивание вокруг СВОЕГО слота) — одновременный `approach` на
//      ТОМ ЖЕ кубике перетирается им же на следующем кадре, движение
//      approach визуально пропадает. Поэтому гунация здесь строго БЕЗ
//      approach — ī превращается в e, стоя в своём собственном слоте,
//      зазор до bhava- ещё открыт. Сближение — отдельным шагом ниже,
//      СТРОГО после того, как transform физически «приземлился»
//      (op._landed, после чего сам transform больше не трогает x).
//   2) ОТДЕЛЬНО, ПОСЛЕ гунации — e (уже не ī) approach'ем закрывает
//      первый зазор, придвигаясь к v. Затем t отдельным approach
//      закрывает второй зазор, придвигаясь к e: bhavet становится
//      единым словом.
import { mountSlotExample, centeredStart } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 5-буквенному слову «bhavet» (тот
// же приём, что у rule1/rule42): centeredStart(5)=2.
const START = centeredStart(5); // = 2
//   START+0 = bh ⎫
//   START+1 = a  │
//   START+2 = v  ⎬ bhava- — основа, целиком, не участвует в самом
//   START+3 = a  │ событии (исчезает; сюда же придвинется e)
//   [START+4 — зазор №1: bhava- и суффикс -ī- падают раздельно]
//   START+5 = ī  ⎭ суффикс оптатива — гунируется в e на месте, потом сдвигается
//   [START+6 — зазор №2: суффикс и окончание -t падают раздельно]
//   START+7 = t  — окончание 3 sg., придвигается ПОСЛЕДНИМ, отдельно
export const data = {
  initial: [
    { slot: START + 0, tr: 'bh' },
    { slot: START + 1, tr: 'a' },
    { slot: START + 2, tr: 'v' },
    { slot: START + 3, tr: 'a' },
    { slot: START + 5, tr: 'ī' },
    { slot: START + 7, tr: 't' },
  ],

  steps: [
    { kind: 'rule', ruleNum: 2, start: 2700, end: 10500, activeSlots: [START + 3, START + 4, START + 5, START + 6, START + 7], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Влияние: конец основы (a) требует гунации соседнего простого
    // гласного (ī) — тот же приём, что у agnayas (influence через
    // зазор, ringHoldDur держит сустейн-кольцо примерно до посадки).
    { type: 'influence', from: START + 3, to: START + 5, start: 2700, ringHoldDur: 4000 },

    // ī → e, дефолтная гуна (spinTurns:1, серебро), НА МЕСТЕ — тот же
    // разрыв между influence.start и transform.start (2600мс), что и у
    // agnayas — даёт зрителю время увидеть влияние до самой реакции.
    { type: 'transform', at: START + 5, toGlyph: 'e', start: 5300, spinTurns: 1, label: 'guṇa' },

    // a уходит вниз тихо — условие, не содержание правила (см. rule42,
    // тот же приём и тот же термин lopa для nimitta-элизии).
    { type: 'elide', at: START + 3, start: 6500, quiet: true, label: 'lopa' },

    // e закрывает первый зазор — СТРОГО после посадки transform (t=1,
    // 5300+900+2000=8200), иначе конфликт с боковым раскачиванием
    // transform (см. комментарий выше). Простое «совместимое
    // примагничивание», без реакции.
    { type: 'approach', movers: [START + 5], target: START + 3, start: 8300, approachDur: 900, distance: 2.0, retreat: false, pulse: false, jitterAmp: 0 },

    // t закрывает второй зазор — ОТДЕЛЬНО, ПОСЛЕ того как e уже встала
    // на место (прямая правка пользователя: «сначала гунация, потом
    // придвинется T»).
    { type: 'approach', movers: [START + 7], target: START + 5, start: 9300, approachDur: 1100, distance: 3.0, retreat: false, pulse: false, jitterAmp: 0 },

    // settle не прописан — считается автоматически.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
