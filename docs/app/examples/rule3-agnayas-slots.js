// agnayas (правило 3) на слот-движке — замена старого rule3-agnayas.js.
// Данные вынесены СЮДА, а не хранятся дублем в test-slot-engine.html и в
// основном приложении — оба места импортируют этот файл, меняется только
// то, ЧТО вызывает mount() (изолированная тестовая страница или сам тренажёр).
// Контракт mount(container) → { unmount, replay } — тот же, что был у старого
// rule3-agnayas.js (см. sanskrit-sandhi-app.html, mountAnimExample) — движок
// (mountSlotExample) уже возвращает ровно эту форму, обёртка не нужна.
import { mountSlotExample, slotX } from '../lib/slot-engine.js';

// agnayas: a-g-n-i-[пусто]-a-s, слоты 1-7 (центрировано)
export const data = {
  initial: [
    { slot: 1, tr: 'a' },
    { slot: 2, tr: 'g' },
    { slot: 3, tr: 'n' },
    { slot: 4, tr: 'i' },
    { slot: 6, tr: 'a' },
    { slot: 7, tr: 's' },
  ],

  // ШАГИ вместо ручных dim-окон: движок сам притеняет всё, что не входит в
  // activeSlots текущего шага, и сам снимает притенение к концу последнего
  // шага (плавно, перед settle).
  //
  // МЕЖДУ шагами явный ЗАЗОР (grammar.end=7300, rule.start=8900) — движок сам
  // превращает такой зазор в паузу-проявление: все буквы разом становятся
  // активны и возвращаются к своим истинным цветам — сигнал «шаг закончен».
  //
  // ВСЕ числа ПОСЛЕ transform.start сдвинуты на +600мс относительно
  // первоначальной версии — прямое следствие замедления MS_PER_360 (было
  // 1400мс/оборот, стало 2000мс/оборот, разница ×1 оборот = 600мс) по
  // прямому замечанию пользователя после живой проверки: гунация читалась
  // слишком быстро. Сдвиг СОХРАНЯЕТ прежний ритм (те же паузы/буферы между
  // событиями), просто откладывает всё, что зависит от фактического
  // приземления вращения, ровно на разницу в его длительности — без этого
  // «правило 3» стартовало бы всего через 100мс после реального конца
  // вращения (было 700мс запаса).
  steps: [
    // грамматика: гунирование i→e вызвано контекстом — весь хвост -as целиком
    // (слоты 6+7), не одна буква A. {word:2} — общая формула («вторая часть
    // примера целиком», см. computeWordGroups/resolveSlotRef в slot-engine.js).
    { kind: 'grammar', start: 2600, end: 7300, activeSlots: [4, { word: 2 }] },
    // правило 3: несовместимость E+A (approach) и сам распад (split). На
    // этом шаге взаимодействуют только E и A — S (слот 7) притенён вместе с
    // фоном, хотя физически продолжает двигаться рядом с A (approach.movers
    // ниже смещает весь хвост -as как единое целое).
    // color: 0xAFBFD4 — тот же hex, что у .c1 в sanskrit-sandhi-app.html
    // (тир внутренних сандхи, к которому отнесено правило 3, g:'c1' в
    // массиве RULES) — кнопка «правило 3» в ленте того же цвета, что и
    // карточка этого правила на панели слева в основном приложении.
    // primary:true — единственное правило примера, крупный и цветной чип.
    { kind: 'rule', ruleNum: 3, start: 8900, end: 16750, activeSlots: [4, 5, 6], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // волна влияния: причина гунирования И (слот 4) — ВСЯ единица -as (оба
    // слота, 6 и 7), не одна буква A. ringHoldDur продлевает сустейн-кольца
    // на источниках до конца связанной трансформации (transform ниже
    // стартует в 5300, длится 2000 — заканчивается в 7300, ровно конец
    // шага «грам.»).
    { type: 'influence', from: { word: 2 }, to: 4, start: 2700, ringHoldDur: 4600 },

    // гунирование: i → e, на месте (слот 4)
    { type: 'transform', at: 4, toGlyph: 'e', toColor: 0x7DCFCA, start: 5300, spinTurns: 1, label: 'guṇa' },

    // иллюстрация несовместимости: весь хвост -as подходит к Е (не одна
    // буква), задерживается, пружинисто отскакивает назад — это и запускает
    // распад. Старт — 8900, синхронно с началом шага «правило 3».
    { type: 'approach', movers: { word: 2 }, target: 4, start: 8900, distance: 0.5, pulse: true },

    // распад: e уходит в отстойник, a и y прилетают.
    {
      type: 'split', at: 4, start: 11650, label: 'ayādi',
      holdOffset: { x: -1.6, y: 2.4, z: 0.4 },
      arrivals: [
        { into: 'a', newSlot: 4, from: { x: slotX(4) + 1.0, y: 2.5, z: -1.5 }, delay: 500, dur: 1600, arcHeight: 0.9 },
        { into: 'y', newSlot: 5, from: { x: slotX(5) + 1.3, y: 3.0, z: -1.8 }, delay: 0,   dur: 1850, arcHeight: 1.3 },
      ]
    },

    // settle не прописан вручную — считается автоматически: 1с после того,
    // как последняя буква вернёт истинный цвет.
  ]
};

export function mount(container) {
  return mountSlotExample(container, data);
}
