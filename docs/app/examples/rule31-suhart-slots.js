// suhārd «друг» → suhārt (перед паузой) — правило 31 на слот-движке.
//
// РАЗБОР ФОРМЫ. suhārd- «друг» (su- «хороший» + hārda- «сердечный»,
// бахуврихи, «имеющий доброе сердце») — согласнoосновное сущ. муж. рода
// (корневой тип склонения, основа оканчивается прямо на согласный d, без
// тематического гласного). Им.п.ед.ч. строится присоединением окончания
// -s прямо к основе: suhārd+s.
//
// ПОЛНАЯ ЦЕПОЧКА (Уитни, §150/§150b/§141/§159 — три отдельных правила,
// сверено дословно по Wikisource; АНИМИРУЕТСЯ только последнее звено,
// первые два — ГОТОВОЕ состояние слова к началу сцены, тот же приём, что
// devās в правиле 55):
//  1. Правило 9 (W150, «if two or more [consonants] would etymologically
//     occur [at the end of a word], the last is dropped, and again the
//     last») — конечное скопление согласных на конце слова сокращается
//     до ОДНОЙ буквы, отбрасывая с конца: «rds» (r+d+s) дало бы просто
//     «r», если бы правило 9 сработало без исключений.
//  2. Правило 8 (W150b, ИСКЛЮЧЕНИЕ из правила 9) — «a non-nasal mute, if
//     radical and not suffixal, is retained after r» — d здесь КОРНЕВОЙ
//     (часть hārda-, не окончание), стоит после r → НЕ отбрасывается,
//     отбрасывается только суффиксальное -s. Уитни приводит ИМЕННО ЭТОТ
//     пример дословно: «suhā́rt from suhārd» (§150b). Итог первых двух
//     шагов — «suhārd» (r+d уцелели, s отброшено) — ГОТОВОЕ состояние,
//     с которого начинается сцена.
//  3. Правило 31 (W141, W159; Pāṇini 8.4.54–56 abhyāse carca / khari ca /
//     vāvasāne — традиционный термин cartva, चर्त्व) — звонкий смычный d
//     не может стоять на конце слова ПЕРЕД ПАУЗОЙ (концом произнесения) —
//     оглушается в своего глухого партнёра по той же варге, t. ЭТО
//     единственное анимируемое событие.
//
// МЕХАНИКА. d и t — парные звуки внутри одной варги (зубной ряд t/th/d/
// dh/n, звонкий/глухой непридых.) — ТА ЖЕ операция, что jaśtva у vāk asti/
// taddhiraṇyam (там t→d, здесь d→t, направление противоположное) —
// `TRANSFORM_KIND.vargaPair` (180°, противолежащая грань), без изменений
// движка. БЕЗ `influence` — у события НЕТ соседа-причины: триггер
// позиционный (конец слова перед паузой/тишиной), не соседняя буква,
// показать «откуда пришло влияние» физически нечем (тот же случай, что
// уже отмечен для правила 13, 2D-only: «без соседней буквы-причины —
// просто позиция перед окончанием»). Пауза-осознание самого `transform`
// (пульс+кольца, anticipateDur) — единственный сигнал «сейчас что-то
// произойдёт», без указания на конкретного виновника; причина объяснена
// словами в тексте примера, не может быть показана линией к соседу.
// clearance — ДЕФОЛТ (+0.35, вправо) корректен без переопределения: d —
// последняя буква слова, справа пусто (край раскладки), слева — r
// (занято) — раскачивание уже идёт в пустую сторону.
//
// Подпись пилюли — 'cartva' (चर्त्व, устоявшийся термин традиции именно
// для этой замены — звонкий/придыхательный → глухой непридыхательный
// перед глухим согласным ИЛИ паузой, Pāṇini 8.4.54–56).
