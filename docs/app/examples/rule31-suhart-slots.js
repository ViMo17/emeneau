// su-hārd- + -s → suhārt (перед паузой, avasāna) — правила 8/9/31 на
// слот-движке, все три на одном слове.
//
// РАЗБОР ФОРМЫ. suhārd- «друг» (su- «хороший» + hārda- «сердечный»,
// бахуврихи, «имеющий доброе сердце») — согласнoосновное сущ. муж. рода
// (корневой тип склонения, основа оканчивается прямо на согласный d, без
// тематического гласного). Им.п.ед.ч. строится присоединением окончания
// -s прямо к основе: suhārd+s.
//
// ПОЛНАЯ ЦЕПОЧКА ИЗ ТРЁХ ПРАВИЛ (Уитни §150/§150b/§141/§159, сверено
// дословно по Wikisource) — ЗДЕСЬ, В ОТЛИЧИЕ ОТ ПЕРВОЙ ВЕРСИИ ЭТОГО
// ФАЙЛА, АНИМИРУЮТСЯ ВСЕ ТРИ, не только последняя (прямая правка
// пользователя: «правило 8 анимируется по шагам, в т.ч. правило 9
// покажет отсечение s, а правило 8 — невозможность отсечения [корневого
// согласного]» — раз все кубики понятны, нет причины скрывать первые два
// шага за кадром):
//  1. Правило 9 (W150, «if two or more [consonants] would etymologically
//     occur [at the end of a word], the last is dropped, and again the
//     last») — конечное скопление согласных «r-d-s» сокращается с конца:
//     суффиксальное -s (окончание Nom.sg.) ОТСЕКАЕТСЯ. РЕАЛЬНЫЙ `elide`
//     (label:'lopa') — первое применение самого правила 9 в 3D вообще.
//  2. Правило 8 (W150b, ИСКЛЮЧЕНИЕ из правила 9) — «a non-nasal mute, if
//     radical and not suffixal, is retained after r»: d — КОРНЕВОЙ (часть
//     hārda-, не окончание), стоит после r → НЕ отбрасывается, хотя по
//     общей логике правила 9 мог бы. Уитни приводит ИМЕННО ЭТОТ пример
//     дословно: «suhā́rt from suhārd» (§150b). У правила 8 НЕТ
//     собственной операции движка — оно показано ЧИСТЫМ КОНТРАСТОМ: пока
//     s (шаг 1) исчезает, d на экране остаётся НЕТРОНУТЫМ рядом — сама
//     стабильность d и есть демонстрация исключения, отдельного action
//     для «правила 8» в `ops` нет и не должно быть.
//  3. Правило 31 (W141, W159; Pāṇini 8.4.54–56 abhyāse carca / khari ca /
//     vāvasāne — традиционный термин cartva, चर्त्व) — звонкий смычный d,
//     оказавшийся ПЕРЕД ПАУЗОЙ (концом произнесения, avasāna), не может
//     оставаться звонким — оглушается в своего партнёра по той же варге,
//     t. Показано через `influence`+`transform` — единственная реальная
//     анимируемая сандхи-замена звука на этом слове.
//
// МАРКЕР ПАУЗЫ (`avasāna`, «।», U+0964 DEVANAGARI DANDA) — НОВАЯ,
// СОЗНАТЕЛЬНАЯ ОГОВОРЕННАЯ ОГОВОРКА к принципу «один кубик = одна
// фонема» (Часть 3 CLAUDE.md): у события правила 31 НЕТ физического
// соседа-причины — триггер ПОЗИЦИОННЫЙ (конец слова перед паузой), и без
// зримого источника `influence` не может показать, ОТКУДА идёт причина
// (та же проблема уже отмечена для правила 13, 2D-only). Решение — прямая
// правка пользователя: данда («।») — не орфографический разделитель ФРАЗ
// вообще (как могло бы показаться), а ТОЧНО тот случай — Pāṇini сам
// определяет avasāna как «пауза» (1.4.110 avasānaṃ viramaḥ) именно на
// границе высказывания/его значимой части, где danda и ставится на
// письме — санскритская традиция уже связывает эти два понятия, не
// изобретаем связь заново. Кубик с данной как `tr` НЕ фонема — `colorFor`
// уже штатно даёт ему нейтральный `COL_DIM` без единой новой строчки
// движка (тот же путь, что уже проверен на аваграхе, rule50, «'», W175a).
// Присутствует С САМОГО НАЧАЛА (падает вместе со всеми буквами) — пауза
// не «наступает», она есть всегда как граница высказывания, к которой
// прижимается конец слова; после того как -s (шаг 1) освобождает слот
// перед ней, данда физически придвигается (`approach`, закрывает зазор
// на 1 слот — тот же приём, что и закрытие зазора после elide в rule55),
// и лишь потом становится источником `influence` для cartva.
//
// ГЕОМЕТРИЯ ВРАЩЕНИЯ: после того как данда придвинулась, у d ОБА соседа
// заняты (r слева, данда справа, без единого зазора) — та же ситуация,
// что уже дважды встречалась (rule2, rule6): `clearance:0` (раскачивания
// вбок нет, некуда), `clearanceZ:-0.5` (выдвижение от камеры спасает от
// прохождения сквозь текстуру соседей на диагоналях вращения).
import { mountSlotExample, centeredStart, TRANSFORM_KIND } from '../lib/slot-engine.js';

// Раскладка: centeredStart(8)=1 — совпадает с centeredStart(7)=1 (итоговое
// 7-тайловое состояние после elide+approach), нет конфликта между
// «центрировать по начальному» и «центрировать по итоговому» (тот же
// урок, что и у rule42) — обе формулы дают одно и то же START.
const START = centeredStart(8); // = 1
//   START+0 = s ⎫
//   START+1 = u │ su- — приставка бахуврихи «хороший»
//   START+2 = h ⎬
//   START+3 = ā │ hārda- — основа «сердечный» (корневой тип склонения)
//   START+4 = r │
//   START+5 = d ⎭ (корневой, останется после шага 1, станет t на шаге 3)
//   START+6 = s   — окончание Nom.sg. (суффиксальное, отсечётся шагом 1)
//   START+7 = ।   — avasāna (пауза), маркер, присутствует с самого начала
export const data = {
  initial: [
    { slot: START + 0, tr: 's' },
    { slot: START + 1, tr: 'u' },
    { slot: START + 2, tr: 'h' },
    { slot: START + 3, tr: 'ā' },
    { slot: START + 4, tr: 'r' },
    { slot: START + 5, tr: 'd' },
    { slot: START + 6, tr: 's' },
    { slot: START + 7, tr: '।' },
  ],

  steps: [
    // Шаг «правило 9» (с явным контрастом правила 8 в тексте): s
    // отсекается, d рядом остаётся нетронутым, данда придвигается.
    { kind: 'rule', ruleNum: 9, start: 3220, end: 7920, activeSlots: [START + 5, START + 6, START + 7], color: 0xAFBFD4, primary: true },
    // Шаг «правило 31»: cartva, d→t перед паузой.
    { kind: 'rule', ruleNum: 31, start: 7920, end: 14170, activeSlots: [START + 5, START + 7], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Правило 9: суффиксальное -s исчезает без следа — реальный, полный
    // lopa (не quiet: это САМО СОДЕРЖАНИЕ показываемого события, не
    // побочный спутник чего-то ещё). label:'lopa' — уже устоявшийся в
    // проекте термин для «замена на ноль» (P. 1.1.60 adarśanaṃ lopaḥ).
    { type: 'elide', at: START + 6, start: 3220, label: 'lopa' },

    // Данда придвигается на освободившееся место — закрывает зазор от
    // исчезнувшего s (тот же приём, что закрытие зазора в rule55), сразу
    // после того, как elide реально завершился (200мс буфер, то же число,
    // что и там). retreat:false/holdDur:0 — доехала и осталась на месте.
    { type: 'approach', movers: [START + 7], target: START + 5, start: 6620, approachDur: 1200, holdDur: 0, retreat: false, distance: 1.0, jitterAmp: 0, pulse: false },

    // Правило 31/cartva: волна от данды (avasāna, «вот она, пауза») к d —
    // источник пульсирует, у цели (d) материал не трогается (та же схема,
    // что и во всех предыдущих influence — конфликта с сигнальным цветом
    // transform'а ниже нет). Дефолтный ringHoldDur (2500мс) гаснет
    // задолго до activeStart transform'а (11420мс) — усекать не нужно.
    { type: 'influence', from: START + 7, to: START + 5, start: 7920 },

    // d → t, парная замена внутри варги (180°, TRANSFORM_KIND.vargaPair —
    // та же операция, что jaśtva, направление обратное). clearance:0/
    // clearanceZ:-0.5 — оба соседа (r слева, данда справа) теперь заняты
    // без единого зазора, см. геометрический разбор выше.
    { type: 'transform', at: START + 5, toGlyph: 't', start: 10520, ...TRANSFORM_KIND.vargaPair, clearance: 0, clearanceZ: -0.5, label: 'cartva' },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — 10520+900(anticipateDur)+1800(dur,vargaPair)+
    // 250(signalHoldDur)+700(holdDur)=14170).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
