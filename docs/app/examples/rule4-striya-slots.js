// strī- «женщина» + ā → striyā «женщиной» — правило 4 на слот-движке.
//
// РАЗБОР ФОРМЫ. strī- — существительное женского рода, основа на долгий ī
// (Whitney, Declension III, «nadī»-тип: односложная основа на -ī/-ū).
// ā — окончание творительного падежа единственного числа (Instr. sg.) для
// существительных этого типа склонения (ср. nadī+ā→nadyā «рекой», тот же
// механизм). Слово ОДНОСЛОЖНОЕ — это условие, отличающее правило 4 от
// правила 6 (там любые i/u/ṛ, не подпадающие под правило 4).
//
// ИСТОЧНИК (Whitney §129/§129a, сверено дословно по Wikisource, Chapter
// III): §129 — общее правило («the i-vowels, the u-vowels, and ṛ, before
// a dissimilar vowel or diphthong, are regularly converted each into its
// own corresponding semivowel, y or v or r», пример stry asya — здесь ī
// ПОЛНОСТЬЮ становится y, сам гласный не сохраняется). §129a — ИСКЛЮЧЕНИЕ
// («in internal combination the i and u-vowels are not seldom changed
// instead to iy and uv — and this especially in monosyllables»): вместо
// потери гласного целиком (как по общему §129/правилу 6), в
// ОДНОСЛОЖНЫХ основах вставляется ДОПОЛНИТЕЛЬНЫЙ y/v, а сам гласный
// (в краткой форме) остаётся — ī не «превращается» в y, а РАСПАДАЕТСЯ на
// i (короче исходного, но существует) и y (новый звук). Panini 6.4.77
// (aci śnudhātubhruvāṃ yvor iyaṅuvaṅau) описывает ТУ ЖЕ замену (iyaṅ/uvaṅ)
// для финального i/ī/u/ū КОРНЯ и слова bhrū — сутра ДЛЯ strī конкретно
// (не корень и не bhrū) не идентифицирована с уверенностью, открытый
// пункт, не гадать дальше без отдельной проверки.
//
// МЕХАНИКА. Как и в agnayas (правило 3), это ОДИН ЗВУК СТАНОВИТСЯ ДВУМЯ —
// техника `split`, подъём вверх (реестр CLAUDE.md, Часть 4). В отличие от
// agnayas, здесь НЕТ предшествующего грамматического шага (agnayas сперва
// требовал гунации i→e, и только потом распадался результат гунации) —
// ī уже стоит в основе с самого начала, событие ЦЕЛИКОМ — прямое
// следствие столкновения с гласным окончанием (зияние двух гласных
// подряд недопустимо). Один шаг: `approach` (несовместимость, ī и ā
// физически сближаются и отскакивают — тот же приём, что e+a в agnayas)
// → `split` (ī поднимается в отстойник, i возвращается на СВОЁ место,
// y прилетает в слот, зарезервированный пустым с самого начала —
// зеркально позиции Y в agnayas). Параметры arrivals/holdOffset —
// ТЕ ЖЕ числа, что в agnayas (уже визуально подтверждены на этой самой
// геометрии: источник и зарезервированный пустой слот сразу после
// него) — не изобретаются заново.
//
// Подпись пилюли — 'iyaṅ' (Pāṇini, технический термин ИМЕННО для замены
// i/ī→iy, u/ū→uv), НЕ 'ayādi' — тот термин зарезервирован за agnayas
// (дифтонг+гласный→a+полугласный, Whitney §131, другая пара звуков и
// другое традиционное название).
import { mountSlotExample, centeredStart, slotX } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 6-буквенному слову «striyā»:
// centeredStart(6)=2.
const START = centeredStart(6); // = 2
//   START+0 = s ⎫
//   START+1 = t │ strī- — основа целиком, кроме своего последнего звука
//   START+2 = r │
//   START+3 = ī ⎭ (единственный участник распада)
//   [START+4 — зазор: цель прилёта y, изначально пуст, как слот 5 в agnayas]
//   START+5 = ā   — окончание Instr. sg., триггер (не меняется, не движется)
export const data = {
  initial: [
    { slot: START + 0, tr: 's' },
    { slot: START + 1, tr: 't' },
    { slot: START + 2, tr: 'r' },
    { slot: START + 3, tr: 'ī' },
    { slot: START + 5, tr: 'ā' },
  ],

  steps: [
    { kind: 'rule', ruleNum: 4, start: 2700, end: 10550, activeSlots: [START + 3, START + 4, START + 5], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Иллюстрация несовместимости: ā подходит к ī (зияние двух гласных
    // недопустимо), задерживается, отскакивает назад — та же техника, что
    // e+a в agnayas (approach, distance:0.5, pulse:true, дефолтный отскок).
    { type: 'approach', movers: [START + 5], target: START + 3, start: 2700, distance: 0.5, pulse: true },

    // Распад: ī уходит в отстойник, i возвращается на своё место, y
    // прилетает в зарезервированный зазор. Старт — через 100мс после
    // полного завершения отскока (2700+1150+550+950=5350), тот же буфер,
    // что между approach и split в agnayas.
    {
      type: 'split', at: START + 3, start: 5450, label: 'iyaṅ',
      holdOffset: { x: -1.6, y: 2.4, z: 0.4 },
      arrivals: [
        { into: 'i', newSlot: START + 3, from: { x: slotX(START + 3) + 1.0, y: 2.5, z: -1.5 }, delay: 500, dur: 1600, arcHeight: 0.9 },
        { into: 'y', newSlot: START + 4, from: { x: slotX(START + 4) + 1.3, y: 3.0, z: -1.8 }, delay: 0, dur: 1850, arcHeight: 1.3 },
      ],
    },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — 5450+5100=10550, ровно момент завершения угасания ī).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
