// tatra eti → tatraiti (правило 42) на слот-движке — ПЕРВЫЙ настоящий
// пример вриддхи в проекте (гэп из CLAUDE.md, Часть 6, п.6, движковая
// часть — signal:'gold'/matsGold/TRANSFORM_KIND.vrddhi — уже готова).
// Взято НЕ по эстетическому выбору, а по прямому указанию пользователя:
// первое правило из 71 (по номеру), где механизм — настоящая вриддхи, не
// гуна. Правила 2/6 (guṇa) и 36 (RUKI-подобное, НЕ guṇa/вриддхи, см.
// docs/reference/interaction-registry.md) идут раньше по номеру, но не
// подходят; 42 — первое совпадение.
//
// Правило по источнику (data.js, emeno): «Сочетание a или ā с дифтонгом
// заменяется одной морфофонемой, соответствующей долгому дифтонгу»
// (Whitney §127, Pāṇini 6.1.104; ср. правило 1 — тот же класс, но a
// перед УЖЕ долгим дифтонгом au просто поглощается без изменения самого
// дифтонга). e и o в санскритской грамматике — «дифтонги» (гуна-ступень),
// ai/au — «долгие дифтонги» (вриддхи-ступень) — то же вертикальное
// отношение, что между i/u (спад) и e/o (гуна) в правилах 2/6/43, только
// на ступень выше. a — nimitta (влияющая, сама исчезает, «поглощается»
// результатом), e — sthānin (поддающаяся, поднимается до ai).
//
// ГЛАВНЫЙ ПРИНЦИП (CLAUDE.md, Часть 2): граница между tatra и eti —
// внешние сандхи, слова падают РАЗДЕЛЁННЫМИ обычным зазором в один слот
// (тот же приём, что vāk asti/taddhiraṇyam). В отличие от ТЕХ примеров
// (граница остаётся зазором навсегда), здесь результат — ОДНО слитное
// слово «tatraiti»: после того как a исчезает (elide) и e становится ai
// (transform, вриддхи), окончание -ti подъезжает (approach) и закрывает
// СРАЗУ два зазора одним движением — освободившийся слот a И исходный
// зазор границы слов (distance:2, не 1).
//
// Направление раскачивания transform — ВЛЕВО (clearance:-0.35): справа от
// e/ai сосед t (eti), место занято; слева на момент вращения — зазор,
// пусто.
import { mountSlotExample, TRANSFORM_KIND } from '../lib/slot-engine.js';

//   0 = t ⎫
//   1 = a │
//   2 = t ⎬ tatra — первое слово
//   3 = r │
//   4 = a ⎭ (nimitta — исчезнет, поглощена результатом)
//   [5 — зазор: граница между словами]
//   6 = e ⎫ (sthānin — станет ai)
//   7 = t ⎬ eti — второе слово
//   8 = i ⎭
export const data = {
  initial: [
    { slot: 0, tr: 't' },
    { slot: 1, tr: 'a' },
    { slot: 2, tr: 't' },
    { slot: 3, tr: 'r' },
    { slot: 4, tr: 'a' },
    { slot: 6, tr: 'e' },
    { slot: 7, tr: 't' },
    { slot: 8, tr: 'i' },
  ],

  // Один шаг — сама сандхи, без предварительной грамматики (как у vāk
  // asti/śādhi): activeSlots — только настоящие участники (a-nimitta,
  // e/ai-sthānin), остальные буквы обоих слов — контекст, притенены.
  // color: 0xC7BAA8 — тот же hex, что у .eg-chip.c4 (тир 41-49) в
  // sanskrit-sandhi-app.css, сверено перед интеграцией.
  steps: [
    { kind: 'rule', ruleNum: 42, start: 3440, end: 12100, activeSlots: [4, 6], color: 0xC7BAA8, primary: true },
  ],

  ops: [
    // Влияние a→e: непрерывный текстурный пульс на a + бегущие волны.
    // frameSignal:'gold' — прямой запрос пользователя: часть слова,
    // вызывающая необходимость вриддхи, подчёркивается на всю длину
    // золотой сияющей полоской. Одиночный источник — раньше рамка не
    // показывалась бы вообще (нечего объединять), frameSignal форсирует
    // показ даже для одной буквы, потому что здесь это не группировка,
    // а сигнал «отсюда идёт вриддхи». ringHoldDur:4000 — тот же интервал,
    // что и в agnayas (гуна): от начала влияния через фиксированный
    // INFLUENCE_TO_TRANSFORM_GAP (2600) и немного в начало самого
    // вращения, не до полного приземления — тот же ритм, что уже
    // одобрен на гунации.
    { type: 'influence', from: 4, to: 6, start: 3540, ringHoldDur: 4000, frameSignal: 'gold' },

    // Само вриддхирование: e → ai, НА МЕСТЕ. TRANSFORM_KIND.vrddhi —
    // 720°, золотой сигнал. clearance:-0.35 — влево, к пустому зазору
    // (слот 5); вправо — занято (t из eti).
    { type: 'transform', at: 6, toGlyph: 'ai', start: 6140, ...TRANSFORM_KIND.vrddhi, clearance: -0.35 },

    // Реакция: a поглощается результатом — та же механика elide
    // (погружение вниз в отстойник, вспышка в момент начала), что и s→∅
    // в śādhi. Старт — вскоре после начала активного вращения e→ai (не
    // одновременно с самим влиянием) — читается как СЛЕДСТВИЕ вриддхи,
    // не независимое совпадающее по времени событие.
    { type: 'elide', at: 4, start: 7340 },

    // Только теперь, когда a исчезло и e уже стало ai, окончание -ti
    // (t, i) подъезжает и закрывает оба зазора одним движением —
    // distance:2 (не 1, как в большинстве примеров): один зазор — от
    // исчезнувшего a, второй — исходная граница слов. Слово становится
    // цельным именно теперь, не раньше.
    { type: 'approach', movers: [6, 7, 8], target: 3, start: 10840, distance: 2, retreat: false, pulse: false, jitterAmp: 0 },

    // settle не прописан — считается автоматически: 1с после того, как
    // последняя буква вернёт истинный цвет.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
