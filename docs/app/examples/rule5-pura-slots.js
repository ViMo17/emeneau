// pṛ- «город» + ā → purā «городом» — правило 5 на слот-движке.
//
// РАЗБОР ФОРМЫ. «pṛ-» здесь — не глагольный корень (у Уитни pṛ- «наполнять»
// отдельно), а корневое (атематическое) СУЩЕСТВИТЕЛЬНОЕ женского рода
// «город» — та же лексема, что даёт им.п.ед.ч. pūḥ, вин.п. puram: основа
// оканчивается на слоговый ṛ, односложная, того же структурного типа, что
// strī-/nadī- в правиле 4 (ṛ-основа, не ī-основа, но тот же принцип —
// «односложная основа теряет НЕ ВЕСЬ гласный, а распадается на короче+
// согласный»). ā — то же окончание Instr. sg., что и в правиле 4
// (strī+ā→striyā, nadī+ā→nadyā) — тот же падеж, тот же тип основы, только
// с ṛ вместо ī.
//
// ИСТОЧНИК (Whitney §242, сверено дословно по Wikisource, полный текст,
// НЕ резюме): важная честная оговорка — Уитни описывает поведение ṛ-корней
// НЕ как чистое фонетическое правило уровня 1–4/6, а как особенность
// ОГРАНИЧЕННОГО списка корней («about a dozen quotable roots»), причём
// «more irregularly, in a part of the forms» — то есть ОДИН и тот же
// корень может давать то ar (гуна), то ir, то ur в РАЗНЫХ формах не вполне
// предсказуемо; «the treatment of such roots has to be described in
// speaking of each formation». Формулировка Эменó («после губного → ur,
// иначе → ir; перед гласным кратко, иначе долго») — рабочее упрощение
// ИМЕННО для «хорошо себя ведущих» корней на губной (pṛ, mṛ, vṛ у Уитни
// §242c), не универсальный закон на весь список Уитни (где, например, tṛ
// — корень БЕЗ губного — всё равно иногда даёт ur: turyāma, наряду с
// ожидаемым ir/ar). Оба примера, которые даёт сам Эменó, при внимательной
// проверке ПОДТВЕРЖДАЮТ его правило дословно, не противоречат ему:
// kṛ-+ati→kirati (ati начинается с гласного a → короткое ir, k не губной →
// i-ряд) и kṛ-+yate→kīryate (yate начинается с СОГЛАСНОГО y, не с гласного,
// несмотря на то что сам показатель пассива фонетически «полугласный», —
// поэтому здесь ветка «не перед гласным» → долгое īr) — оба варианта
// правила у Эменó срабатывают корректно на собственных примерах, просто
// не покрывают ВЕСЬ список нерегулярных корней Уитни целиком.
// Panini 6.4.77 (aci śnudhātubhruvāṃ yvor iyaṅuvaṅau, см. правило 4) —
// та же ПО ДУХУ операция (короткий гласный + добавочный согласный вместо
// полной потери гласного), но сутра ДОСЛОВНО называет только y/v (для i/u)
// — r (для ṛ) в её тексте не упомянут; параллельная сутра именно для ṛ→
// ir/ur не найдена, термин пилюли ниже — временный, не выдуманный
// санскритский, см. реестр CLAUDE.md.
//
// МЕХАНИКА. Структурно — ТА ЖЕ операция, что e→a+y в agnayas и ī→i+y в
// правиле 4: один звук становится двумя, `split`, БЕЗ предшествующего
// грамматического шага (ṛ уже стоит в основе, событие — прямое следствие
// столкновения с ā). Единственное отличие от правила 4 — результат НЕ
// «i/u + y/v», а «i/u + r» (ṛ не полностью вокалический, распадается на
// краткий гласный + СОГЛАСНЫЙ r, не полугласный), и выбор i- или u-ряда
// определяется предшествующим согласным (p — губной → u). Геометрия —
// ЧИСЛЕННО СКОПИРОВАНА с agnayas/правила 4 (approach: несовместимость,
// отскок; split: holdOffset/arrivals — те же параметры, уже подтверждённая
// хореография на той же самой раскладке — источник и пустой слот сразу
// после него).
import { mountSlotExample, centeredStart, slotX } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 4-буквенному слову «purā»:
// centeredStart(4)=3.
const START = centeredStart(4); // = 3
//   START+0 = p ⎫ pṛ- — вся основа (два звука)
//   START+1 = ṛ ⎭ (единственный участник распада)
//   [START+2 — зазор: цель прилёта r, изначально пуст, как слот 5 в правиле 4]
//   START+3 = ā   — окончание Instr. sg., триггер (не меняется, не движется)
export const data = {
  initial: [
    { slot: START + 0, tr: 'p' },
    { slot: START + 1, tr: 'ṛ' },
    { slot: START + 3, tr: 'ā' },
  ],

  steps: [
    { kind: 'rule', ruleNum: 5, start: 2700, end: 10550, activeSlots: [START + 1, START + 2, START + 3], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Иллюстрация несовместимости: ā подходит к ṛ (зияние недопустимо),
    // задерживается, отскакивает назад — та же техника, что в agnayas и
    // правиле 4 (approach, distance:0.5, pulse:true, дефолтный отскок).
    { type: 'approach', movers: [START + 3], target: START + 1, start: 2700, distance: 0.5, pulse: true },

    // Распад: ṛ уходит в отстойник, u (короткое — окончание ā начинается с
    // гласного, ветка «перед гласным») возвращается на своё место, r
    // прилетает в зарезервированный зазор. p — губной согласный, поэтому
    // u-ряд, не i-ряд (см. разбор выше). Старт — через 100мс после полного
    // завершения отскока (2700+1150+550+950=5350), тот же буфер, что и в
    // agnayas/правиле 4.
    {
      type: 'split', at: START + 1, start: 5450, label: 'огласовка ṛ',
      holdOffset: { x: -1.6, y: 2.4, z: 0.4 },
      arrivals: [
        { into: 'u', newSlot: START + 1, from: { x: slotX(START + 1) + 1.0, y: 2.5, z: -1.5 }, delay: 500, dur: 1600, arcHeight: 0.9 },
        { into: 'r', newSlot: START + 2, from: { x: slotX(START + 2) + 1.3, y: 3.0, z: -1.8 }, delay: 0, dur: 1850, arcHeight: 1.3 },
      ],
    },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — 5450+5100=10550, ровно момент завершения угасания ṛ).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
