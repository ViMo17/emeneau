// devas + asti → devo'sti (правило 50) на слот-движке. ПЕРВЫЙ реальный тест
// слияния ДВУХ РАЗНЫХ звуков (merge/split-эквивалент до сих пор проверялся
// только на самоподобии a+a→ā, rule7) — закрывает гэп CLAUDE.md Часть 6, п.1.
//
// Правило по источнику (data.js, emeno, W175a, P6.1.113): «Сочетание
// финального -as с начальным a-: -as → -o, а a- → аваграха». ДВА отдельных
// события одной формулировки, не одно трёхзвучное слияние — расхождение с
// прежним текстом `EXAMPLES[50].roleDemo` («оба компонента источника
// участвуют разом») найдено и исправлено при подготовке этого примера (тот
// текст противоречил уже выверенному в Фазе 2 тексту `emeno`).
//
// МЕХАНИКА (по прямой раскладке пользователя, НЕ merge вдоль ряда, а через
// отстойник — та же визуальная логика, что и у split, только «наоборот»,
// 2 источника → 1 результат):
//   1) a (asti) влияет на ВЕСЬ кластер -as (оба звука devas) — до начала
//      реакции.
//   2) «as» поднимается вверх, в отстойник (ДВА параллельных `split`,
//      каждый на свой звук — a и s, — синхронизированы так, чтобы оба
//      кубика угасали в один и тот же момент, читались как единое целое).
//   3) «o» прилетает на замену — единственный `arrival`, привязан к тому
//      split, что был на слоте будущего o (слот 3, рядом с v — без
//      внутреннего разрыва в «devo»; освободившийся слот 4 сливается с уже
//      существующим внешним зазором, не создаёт нового отдельного).
//   4) ОДНОВРЕМЕННО с (2) — a в asti крутится один оборот (360°) и
//      заменяется на аваграху (') — `transform`, НЕ elide: буква не
//      пропадает, а становится другим, видимым символом.
//   5) ПОСЛЕДНИЙ шаг — вторая часть слова («'sti») подъезжает к первой,
//      закрывая расширившийся (после ухода слота 4) зазор до стандартной
//      ширины внешней границы — тот же приём `approach(retreat:false)`,
//      что уже отработан на rule55.
import { mountSlotExample, slotX } from '../lib/slot-engine.js';

//   0 = d ⎫
//   1 = e │
//   2 = v ⎬ devas — по буквам полностью
//   3 = a │ (кластер -as: оба звука сольются, «o» приземлится ИМЕННО сюда)
//   4 = s ⎭ (после события — свободен, сливается с внешним зазором)
//   [5 — зазор: граница слов, ВНЕШНЕЕ сандхи, стандартная ширина 1 слот]
//   6 = a   ⎫ (nimitta — причина; НЕ исчезает, становится аваграхой)
//   7 = s   │
//   8 = t   ⎬ asti — по буквам полностью
//   9 = i   ⎭
export const data = {
  initial: [
    { slot: 0, tr: 'd' },
    { slot: 1, tr: 'e' },
    { slot: 2, tr: 'v' },
    { slot: 3, tr: 'a' },
    { slot: 4, tr: 's' },
    { slot: 6, tr: 'a' },
    { slot: 7, tr: 's' },
    { slot: 8, tr: 't' },
    { slot: 9, tr: 'i' },
  ],

  // Единственный шаг — само правило 50 целиком (обе его половины одной
  // формулировки источника, не цепочка разных правил). activeSlots —
  // ТОЛЬКО реальные участники: 3,4 (кластер -as → o), 6 (a → аваграха).
  steps: [
    { kind: 'rule', ruleNum: 50, start: 3730, end: 12780, activeSlots: [3, 4, 6], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Влияние: a из asti тянется к ОБОИМ звукам кластера -as разом — два
    // отдельных вызова (у influence одна цель на вызов), но одновременно.
    { type: 'influence', from: 6, to: 3, start: 3730, ringHoldDur: 3200 },
    { type: 'influence', from: 6, to: 4, start: 3730, ringHoldDur: 3200 },

    // «AS» поднимается вверх, в отстойник — ДВА параллельных split, один
    // на a (слот 3, сюда же вернётся «o»), один на s (слот 4, ничего не
    // прилетает взамен). holdDur слота 4 подобран так, чтобы оба кубика
    // угасли в ОДИН и тот же момент (compareReadyAt у слота 3 длиннее
    // из-за arrival, 1900мс vs 1300мс riseDur — разница восполнена явным
    // holdDur=1600 вместо дефолтных 1000, чтобы «as» читалось как единое
    // целое, не как два отдельно тающих кубика).
    {
      type: 'split', at: 3, start: 6330, label: 'Слияние',
      holdOffset: { x: -1.6, y: 2.4, z: 0.4 },
      arrivals: [
        { into: 'o', newSlot: 3, from: { x: slotX(3) + 1.0, y: 2.8, z: -1.6 }, delay: 200, dur: 1700, arcHeight: 1.0 },
      ],
    },
    {
      type: 'split', at: 4, start: 6330,
      holdOffset: { x: -1.6, y: 2.4, z: 0.4 },
      holdDur: 1600,
      arrivals: [],
    },

    // ОДНОВРЕМЕННО с подъёмом «as» — a в asti оборачивается (360°, обычный
    // гунация-темп по MS_PER_360) и становится аваграхой. signal:'blank' —
    // это не огласовка (не гуна/вриддхи), серебро/золото здесь неуместны.
    // colorFor("'") падает в нейтральный COL_DIM (тот же путь, что у
    // анусвары/висарги — «без единого места образования»), новый код не
    // нужен.
    { type: 'transform', at: 6, toGlyph: "'", start: 6330, spinTurns: 1, signal: 'blank', label: 'Аваграха' },

    // ПОСЛЕДНИЙ шаг: «'sti» подъезжает к «devo», закрывая расширившийся
    // (после ухода слота 4) зазор до стандартной ширины внешней границы —
    // тот же приём, что уже на rule55 (retreat:false, «совместимое
    // примагничивание»). Старт — после того, как оба split реально
    // угасли (6330+900анц+1900+1600=10730... точнее — оба фейда
    // заканчиваются на 11230), с буфером.
    { type: 'approach', movers: [6, 7, 8, 9], target: 3, start: 11430, approachDur: 1200, distance: 1.0, retreat: false, pulse: false, jitterAmp: 0 },

    // settle не прописан — считается автоматически.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
