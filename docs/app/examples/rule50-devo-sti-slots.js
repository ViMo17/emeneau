    // landsOnOppositeFace) — не трогает MS_PER_360 глобально, значит не
    // задевает гунацию/вриддхи нигде в приложении. Численно: оборот
    // заканчивается на 1100мс ПОЗЖЕ, чем O садится на своё место (в
