    // золото неуместны; colorFor("'") падает в нейтральный COL_DIM без
    // нового кода. clearance:-0.35 — влево, к пустому зазору-границе слов
    // (слот 5), не вправо (задело бы текстуру s, слот 7).
    //
    // dur:3000 (было 2000 = обычный темп по MS_PER_360) — по прямому
    // запросу: оборот должен быть заметно медленнее, иначе внимание целиком
