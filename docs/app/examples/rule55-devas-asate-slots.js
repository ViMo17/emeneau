// devās + āsate → devā āsate (правило 55) на слот-движке — второй реальный
// тест цепочки правил (после taddhiraṇyam), но другого типа: там оба звена
// цепочки — независимые внешние сандхи одной и той же границы; здесь
// звено 1 (правило 7, слияние a+a→ā) — ВНУТРЕННЕЕ событие, ещё при
// образовании самого devās (deva- + окончание им.п.мн.ч. -as), а звено 2
// (правило 55, элизия -s) — уже настоящее ВНЕШНЕЕ сандхи на границе слов
// devās|āsate. Проверено дословно по источнику (Эмено, W177): «Финальный
// -ās переходит в -ā перед всеми звонкими звуками. Например: devās āsate →
// devā āsate «боги сидят»» — тот же пример, что уже используется в
// data.js (EXAMPLES[55].roleDemo, оба шага, tag:'7'+tag:'55', сверено на
// фазе 2 академической проверки).
import { mountSlotExample } from '../lib/slot-engine.js';

// deva- «бог» (основа m.) + -as (окончание им.п.мн.ч., → сольётся в -ās по
// правилу 7) + āsate «сидят» (3 л. мн.ч. наст.вр. ās- «сидеть»).
// Атомарно: d,e,v,a + a,s + ā,s,a,t,e = 11 фонем — больше, чем N_SLOTS=10,
// поэтому по краям (дальше всего от места события) сжаты два инертных
// блока (лимит ≤3 буквы, см. CLAUDE.md Часть 3): «de» (2 буквы, ближе к
// лимиту не нужно — v и a рядом с границей событий остаются
// индивидуальными) и «ate» (3 буквы, хвост āsate — участвует только его
// первый звук ā). Занят весь диапазон 0..9, как у taddhiraṇyam.
//   0 = «de» (сжатый инертный блок — d,e самой deva-, к событию не имеют
//       отношения)
//   1 = v   ⎫ deva- индивидуально до самой границы
//   2 = a   ⎭ (финальный гласный основы — сольётся со слотом 4)
//   [3 — зазор: морфологическая граница deva-|-as, закроется слиянием]
//   4 = a   ⎫ окончание -as: начальный гласный (примет слог a, станет ā)
//   5 = s   ⎭ окончание -as: финальный согласный (переживёт слияние как
//       -s основы devās, исчезнет на шаге 2)
//   [6 — зазор: граница слов devās|āsate, ВНЕШНЕЕ сандхи — не
//       схлопывается никогда, тот же принцип, что у vāk asti/taddhiraṇyam]
//   7 = ā     — āsate: начальный долгий гласный, причина элизии (звонкий)
//   8 = s     — āsate индивидуально (в непосредственном контакте с ā)
//   9 = «ate» (сжатый инертный хвост āsate — a,t,e, к событию не имеют
//       отношения)
export const data = {
  initial: [
    { slot: 0, tr: 'de' },
    { slot: 1, tr: 'v' },
    { slot: 2, tr: 'a' },
    { slot: 4, tr: 'a' },
    { slot: 5, tr: 's' },
    { slot: 7, tr: 'ā' },
    { slot: 8, tr: 's' },
    { slot: 9, tr: 'ate' },
  ],

  // ДВА `rule`-шага подряд, РАЗНЫЕ activeSlots ([2,4] и [5,7]) — в отличие
  // от taddhiraṇyam (там activeSlots шагов совпадали, зазор-проявление
  // пропускался) — здесь состав участников меняется полностью, поэтому
  // между шагами полагается обычное проявление (все буквы кратко видны
  // без притенения), как у agnayas/āsīt. Шаг 1 (правило 7, повторно
  // применённое внутри этого примера) — БЕЗ primary, стандартный охровый
  // цвет вспомогательного шага (см. slot-engine.js). Шаг 2 (правило 55) —
  // главный, ради которого построен весь пример.
  steps: [
    { kind: 'rule', ruleNum: 7, start: 3470, end: 5370, activeSlots: [2, 4], color: 0xAFBFD4 },
    { kind: 'rule', ruleNum: 55, start: 6970, end: 12920, activeSlots: [5, 7], color: 0xAE987A, primary: true },
  ],

  ops: [
    // ШАГ 1 (правило 7, внутреннее событие формирования devās): финальный
    // гласный основы (слот 2) едет к начальному гласному окончания (слот
    // 4) и сливается с ним в ā — та же механика (и то же направление
    // «левая буква едет в слот правой»), что и в rule7-asit.js.
    { type: 'merge', from: 2, at: 4, start: 3470, dur: 1400, toGlyph: 'ā' },

    // ШАГ 2 (правило 55, внешнее сандхи devās|āsate): граница слов не
    // схлопывается (тот же принцип, что у vāk asti/taddhiraṇyam) — ничто
    // никуда не едет, событие происходит НА МЕСТЕ. Влияние идёт через
    // постоянный зазор от ā (причина: звонкий звук) к s (цель) —
    // непрерывный пульс+бегущие волны, тот же приём, что у vāk asti.
    { type: 'influence', from: 7, to: 5, start: 6970, ringHoldDur: 3900 },

    // РЕАКЦИЯ: в отличие от vāk asti (там цель ПРЕВРАЩАЕТСЯ, transform),
    // здесь цель ПРОПАДАЕТ БЕЗ СЛЕДА — elide, погружение вниз (тот же
    // язык, что у śādhi), только БЕЗ предварительного approach (в śādhi
    // approach был нужен, потому что там внутреннее сандхи и окончание
    // физически подъезжает; здесь граница внешняя и постоянная — s
    // реагирует на месте на волну, дошедшую через зазор). start —
    // ровно через 100мс после того, как последняя волна influence
    // (start+2500 при дефолтных waveCount/waveGap/waveTravel) реально
    // достигает цели — та же пауза-буфер, что у vāk asti между influence
    // и transform.
    { type: 'elide', at: 5, start: 9570 },

    // settle не прописан — считается автоматически: см. формулу в
    // slot-engine-mount.js (последний шаг + проявление хвоста + пауза).
  ],
};

