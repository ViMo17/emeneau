// devās + āsate → devā āsate (правило 55) на слот-движке. devās — ГОТОВОЕ
// слово примера (им.п.мн.ч. deva- «бог», как и śās/vāk/tat в других
// примерах не разлагается на более мелкие морфемы на экране: их
// собственное словообразование — предмет ДРУГИХ правил, уже показанных
// отдельно, здесь не переигрывается). Единственное событие — само правило
// 55: внешнее сандхи devās|āsate, финальный -s исчезает перед звонким
// начальным ā. Проверено дословно по источнику (Эмено, W177): «Финальный
// -ās переходит в -ā перед всеми звонкими звуками. Например: devās āsate →
// devā āsate «боги сидят»».
import { mountSlotExample } from '../lib/slot-engine.js';

// devās «боги» (им.п.мн.ч.) + āsate «сидят» (3 л. мн.ч. наст.вр. ās-).
// Граница слов — внешнее сандхи, СТАНДАРТНАЯ ширина зазора в этом проекте
// — 1 слот (vāk asti, taddhiraṇyam). Здесь исчезающая s стоит ВПЛОТНУЮ к
// границе — после elide зазор на кадр становится шире стандартного (2
// пустых слота, побочный эффект освободившегося слота s, не изменение
// самой границы). Финальным `approach` āsate возвращается на стандартное
// расстояние в 1 слот от devā — граница НЕ схлопывается (в один слот, не
// в ноль), это восстановление стандарта, не новый приём. Занятый
// диапазон — 9 позиций (5 devās + 1 зазор + 3 āsate), центрирован по общей
// формуле centeredStart(9)=0 (slot-engine-core.js) — весь единственный
// лишний слот (10-9=1, нечётное число не делится пополам) уходит справа,
// та же неизбежная асимметрия чётности, что и в других примерах.
//   0 = d ⎫
//   1 = e │ devās — по буквам полностью, включая инертные d,e,v
//   2 = v │ (готовое слово, ничего внутри него не меняется)
//   3 = ā │
//   4 = s ⎭ (единственный участник — исчезнет)
//   [5 — зазор: граница слов, ВНЕШНЕЕ сандхи, стандартная ширина 1 слот]
//   6 = ā   ⎫ āsate: начальный долгий гласный — причина элизии (звонкий)
//   7 = s   │ индивидуально, до предела сжатия
//   8 = «ate» (сжатый инертный хвост — a,t,e, к событию отношения не имеют)
//   [9 — не занят: остаток от нечётного span]
export const data = {
  initial: [
    { slot: 0, tr: 'd' },
    { slot: 1, tr: 'e' },
    { slot: 2, tr: 'v' },
    { slot: 3, tr: 'ā' },
    { slot: 4, tr: 's' },
    { slot: 6, tr: 'ā' },
    { slot: 7, tr: 's' },
    { slot: 8, tr: 'ate' },
  ],

  // Единственный шаг — сама сандхи, без предварительной грамматики (в
  // отличие от agnayas/āsīt — оба слова уже в готовой форме). activeSlots
  // включает ВСЮ группу āsate (6,7,8), не только триггер (6) — во время
  // approach (см. ops) вся группа едет одним куском, разное притенение её
  // частей выглядело бы рвано. Шаг остаётся активным (притенение держится)
  // до конца approach — развидка и settle идут ПОСЛЕ, автоматически.
  steps: [
    { kind: 'rule', ruleNum: 55, start: 3470, end: 10820, activeSlots: [4, 6, 7, 8], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Влияние: непрерывный пульс+бегущие волны через внешний зазор от ā
    // (причина: звонкий звук) к s (цель) — тот же приём, что у vāk asti
    // (там transform на месте; здесь elide на месте — граница внешняя в
    // обоих случаях, физического сближения не требуется для самой сандхи).
    { type: 'influence', from: 6, to: 4, start: 3470, ringHoldDur: 3900 },

    // РЕАКЦИЯ: s пропадает БЕЗ СЛЕДА — elide, погружение вниз (тот же язык,
    // что у śādhi), но БЕЗ approach ДО этого момента: s реагирует на месте
    // на волну, дошедшую через зазор. start — через 100мс после того, как
    // последняя волна influence (start+2500 при дефолтных waveCount/
    // waveGap/waveTravel) реально достигает цели — тот же буфер, что у
    // vāk asti между influence и transform.
    { type: 'elide', at: 4, start: 6070 },

    // ЗАВЕРШЕНИЕ: āsate целиком (6,7,8) подъезжает к devā на стандартное
    // расстояние внешнего сандхи — 1 слот (было 2 после исчезновения s,
    // побочный эффект освободившегося слота, не новая ширина границы).
    // Та же техника «совместимое примагничивание», что у -īt→AS в rule7
    // (retreat:false — доехало и осталось, без отскока несовместимости).
    // start — через 200мс после того, как elide реально завершается
    // (риса+пауза+угасание = 1300+800+1100=3200, т.е. 6070+3200=9270) —
    // сначала виден результат самой сандхи, потом сближение.
    { type: 'approach', movers: [6, 7, 8], target: 3, start: 9470, approachDur: 1200, holdDur: 0, retreat: false, distance: 1.0, jitterAmp: 0, pulse: false },

    // settle не прописан — считается автоматически.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
