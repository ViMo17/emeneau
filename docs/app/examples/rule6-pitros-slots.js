// pitṛ- «отец» + os → pitros «(двух) отцов» — правило 6 на слот-движке.
//
// РАЗБОР ФОРМЫ. pitṛ- «отец» — родственный термин, атематическая основа
// муж. рода на слоговый ṛ (двусложная — pi-tṛ, В ОТЛИЧИЕ от pṛ- в правиле
// 5, которая односложна: pṛ-). os — окончание родительного/местного
// падежа двойственного числа (Gen./Loc. du.) — «(двух) отцов» / «у (двух)
// отцов».
//
// ИСТОЧНИК (Whitney §129, сверено дословно по Wikisource: «The i-vowels,
// the u-vowels, and ṛ, before a dissimilar vowel or diphthong, are
// regularly converted each into its own corresponding semivowel, y or v
// or r»; примеры Уитни там же — ity āha, madhv iva, stry asya). Это ОБЩЕЕ
// правило (в отличие от правила 4/5, W129a — исключение ТОЛЬКО для
// односложных основ/корней: там гласный НЕ теряется целиком, а
// распадается на короче+согласный). pitṛ- ДВУСЛОЖНАЯ — под исключение
// W129a не подпадает, значит действует общее правило: ṛ ПОЛНОСТЬЮ
// становится r, без остатка гласного. Panini 6.1.77 iko yaṇ aci — та же
// операция, ТЕХНИЧЕСКИЙ ТЕРМИН для неё в санскритской грамматике — yaṇ
// (यण्, название самого пратьяхары y-v-r-l, широко используется как имя
// этой замены — «yaṇ sandhi»).
//
// МЕХАНИКА. В отличие от правил 4/5 (split — один звук становится двумя),
// здесь ПОЛНОЦЕННЫЙ `transform` — 1-к-1, ṛ на месте становится r, без
// нового кубика и без остатка. `signal:'blank'` (НЕ серебро — серебро
// строго зарезервировано за гунацией, а замена гласного на полугласный —
// качественно другая операция, не восходящая ступень огласовки) —
// ТА ЖЕ числовая пара `{spinTurns:1, signal:'blank'}`, что уже определена
// как `TRANSFORM_KIND.assimToNeighbor`, но НЕ импортируется под этим
// именем: там она про ассимиляцию согласного по месту образования, здесь
// — про гласный, полностью переходящий в полугласный (иная лингвистическая
// категория за той же геометрией движка). Если третий похожий случай
// понадобится (правило 36, RUKI — см. interaction-registry.md, Часть В,
// п.3, остаётся открытым), тогда будет смысл свести все три под одно имя;
// пока — два реальных случая, преждевременно обобщать одним словом.
// `clearance:0`/`clearanceZ:-0.5` — ṛ стоит ВПЛОТНУЮ к соседям С ОБЕИХ
// СТОРОН (t слева, o справа — раскладка без единого зазора, впервые в
// этой сессии оба соседа заняты разом): бокового раскачивания НЕТ вообще
// (нет пустого места ни в одну сторону — раскачивание к пустому месту,
// раз пустого места нет, лучше отключить, чем выбирать «менее плохую»
// сторону), а выдвижение по Z (та же техника и то же число, что и в
// правиле 2 — там была та же геометрия «оба соседа впритык») спасает от
// прохождения сквозь текстуру соседей на диагональных углах вращения.
// influence НЕ трогает материал цели (ṛ) — пульсирует только источник
// (o), поэтому конфликта с сигнальным материалом transform'а на слоте ṛ
// нет (тот же анализ, что уже подтверждён в agnayas), ringHoldDur можно
// не усекать искусственно.
//
// Подпись пилюли — 'yaṇ' (Pāṇini 6.1.77, устоявшийся термин именно для
// этой замены — не путать с `iyaṅ`/`uvaṅ` у правила 4/5, там ИСКЛЮЧЕНИЕ
// с остатком гласного, здесь ОБЩЕЕ правило без остатка).
import { mountSlotExample, centeredStart } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 6-буквенному слову «pitros»:
// centeredStart(6)=2. Без единого зазора — ṛ становится r НА МЕСТЕ, новый
// кубик не создаётся (в отличие от правил 4/5, split здесь не нужен).
const START = centeredStart(6); // = 2
//   START+0 = p ⎫
//   START+1 = i │ pitṛ- — основа целиком (двусложная)
//   START+2 = t │
//   START+3 = ṛ ⎭ (единственный участник, становится r)
//   START+4 = o ⎫ os — окончание Gen./Loc. du., o — фонетический триггер
//   START+5 = s ⎭ (s к самому событию отношения не имеет, инертный сосед)
export const data = {
  initial: [
    { slot: START + 0, tr: 'p' },
    { slot: START + 1, tr: 'i' },
    { slot: START + 2, tr: 't' },
    { slot: START + 3, tr: 'ṛ' },
    { slot: START + 4, tr: 'o' },
    { slot: START + 5, tr: 's' },
  ],

  // Один шаг — событие целиком фонетическое (любой следующий гласный
  // вызывает переход в полугласный), не грамматическое: activeSlots —
  // ТОЛЬКО реальный триггер (o) и цель (ṛ), не весь хвост «os» — s к
  // причине события отношения не имеет.
  steps: [
    { kind: 'rule', ruleNum: 6, start: 2600, end: 9150, activeSlots: [START + 3, START + 4], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Влияние: непрерывный пульс на o (источник) + бегущие волны к ṛ
    // (цель) — тот же приём, что и грамматический шаг agnayas. ringHoldDur
    // — тот же интервал, что там (4600мс) — конфликта с сигнальным
    // материалом transform'а нет (influence не трогает материал цели, см.
    // разбор выше).
    { type: 'influence', from: START + 4, to: START + 3, start: 2700, ringHoldDur: 4600 },

    // ṛ → r, на месте, полностью (не split — общее правило W129, не
    // исключение W129a). clearance:0 — раскачивания в сторону нет (оба
    // соседа заняты), clearanceZ уводит вращающийся кубик от камеры на
    // пике, чтобы диагональные углы не проходили сквозь текстуру соседей.
    { type: 'transform', at: START + 3, toGlyph: 'r', start: 5300, spinTurns: 1, signal: 'blank', clearance: 0, clearanceZ: -0.5, label: 'yaṇ' },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — момент, когда цвет и пауза-фиксация уже
    // завершены: 5300+900(anticipateDur)+2000(dur)+250(signalHoldDur)+
    // 700(holdDur)=9150).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
