// pitṛ- «отец» + os → pitros «(двух) отцов» — правило 6 на слот-движке.
//
// РАЗБОР ФОРМЫ. pitṛ- «отец» — родственный термин, атематическая основа
// муж. рода на слоговый ṛ (двусложная — pi-tṛ, В ОТЛИЧИЕ от pṛ- в правиле
// 5, которая односложна: pṛ-). os — окончание родительного/местного
// падежа двойственного числа (Gen./Loc. du.) — «(двух) отцов» / «у (двух)
// отцов».
//
// ИСТОЧНИК (Whitney §129, сверено дословно по Wikisource: «The i-vowels,
// the u-vowels, and ṛ, before a dissimilar vowel or diphthong, are
// regularly converted each into its own corresponding semivowel, y or v
// or r»; примеры Уитни там же — ity āha, madhv iva, stry asya). Это ОБЩЕЕ
// правило (в отличие от правила 4/5, W129a — исключение ТОЛЬКО для
// односложных основ/корней: там гласный НЕ теряется целиком, а
// распадается на короче+согласный). pitṛ- ДВУСЛОЖНАЯ — под исключение
// W129a не подпадает, значит действует общее правило: ṛ ПОЛНОСТЬЮ
// становится r, без остатка гласного. Panini 6.1.77 iko yaṇ aci — та же
// операция, ТЕХНИЧЕСКИЙ ТЕРМИН для неё в санскритской грамматике — yaṇ
// (यण्, название самого пратьяхары y-v-r-l, широко используется как имя
// этой замены — «yaṇ sandhi»).
//
// МЕХАНИКА — ПЕРЕСМОТРЕНА (прямая поправка пользователя: «мы
// зарезервировали вращение для гуны, вриддхи, ослабления и смены парных
// согласных — здесь замена, с вылетом вверх в отстойник»). Все четыре
// зарезервированные категории `transform` — это сегмент, ОСТАЮЩИЙСЯ СОБОЙ
// и сдвигающийся ПО СВОЕЙ ЖЕ ОСИ (гуна/вриддхи — вверх по лестнице
// гласного; парная замена — по звонкости/придыхательности ВНУТРИ одной
// варги). ṛ→r — качественно ДРУГОЕ: гласный (слогообразующий сонант)
// категориально становится согласным (неслоговым) — не сдвиг по оси, а
// смена самой природы звука. Это ближе к `split` («одна буква становится
// другой/другими», реестр CLAUDE.md Часть 4) — исходный звук ПОДНИМАЕТСЯ
// в отстойник и исчезает, результат ПРИЛЕТАЕТ отдельным кубиком — чем к
// вращению на месте. Отличие от правил 4/5 — результат ОДИН, не два (r
// замещает ṛ ЦЕЛИКОМ, без остатка краткого гласного), и приземляется он
// СЮДА ЖЕ, в исходный слот ṛ (не в отдельный зарезервированный зазор,
// которого здесь и нет — раскладка pitros без единого зазора). Move
// генерично поддерживает `arrivals` любой длины (agnayas/правило 4/5 —
// 2 элемента; правило 50 — 1 элемент у одного из параллельных split,
// пустой у другого) — split с ОДНИМ элементом, приземляющимся в СВОЙ ЖЕ
// исходный слот, ничего нового в движке не требует. `holdOffset`/
// `arrivals`-числа — те же, что уже подтверждены визуально (agnayas/
// правило 4/5), геометрия подъёма-и-прилёта одинакова независимо от
// того, один результат или два.
//
// Подпись пилюли — 'yaṇ' (Pāṇini 6.1.77, устоявшийся термин именно для
// этой замены — не путать с `iyaṅ`/`uvaṅ` у правила 4/5, там ИСКЛЮЧЕНИЕ
// с остатком гласного, здесь ОБЩЕЕ правило без остатка).
import { mountSlotExample, centeredStart, slotX } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 6-буквенному слову «pitros»:
// centeredStart(6)=2. Без единого зазора — split здесь не нуждается в
// зарезервированном пустом слоте (единственный результат возвращается в
// исходный слот ṛ, а не в соседний).
const START = centeredStart(6); // = 2
//   START+0 = p ⎫
//   START+1 = i │ pitṛ- — основа целиком (двусложная)
//   START+2 = t │
//   START+3 = ṛ ⎭ (единственный участник, становится r)
//   START+4 = o ⎫ os — окончание Gen./Loc. du., o — фонетический триггер
//   START+5 = s ⎭ (s к самому событию отношения не имеет, инертный сосед)
export const data = {
  initial: [
    { slot: START + 0, tr: 'p' },
    { slot: START + 1, tr: 'i' },
    { slot: START + 2, tr: 't' },
    { slot: START + 3, tr: 'ṛ' },
    { slot: START + 4, tr: 'o' },
    { slot: START + 5, tr: 's' },
  ],

  // Один шаг — событие целиком фонетическое (любой следующий гласный
  // вызывает переход в полугласный), не грамматическое: activeSlots —
  // ТОЛЬКО реальный триггер (o) и цель (ṛ), не весь хвост «os» — s к
  // причине события отношения не имеет.
  steps: [
    { kind: 'rule', ruleNum: 6, start: 2600, end: 10400, activeSlots: [START + 3, START + 4], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Влияние: непрерывный пульс на o (источник) + бегущие волны к ṛ
    // (цель) — тот же приём, что и грамматический шаг agnayas. ringHoldDur
    // — тот же интервал, что там (4600мс).
    { type: 'influence', from: START + 4, to: START + 3, start: 2700, ringHoldDur: 4600 },

    // Распад-замена: ṛ уходит в отстойник и исчезает без следа (тает на
    // паузе-сравнении — ждать здесь нечего, второго варианта для
    // сопоставления нет), r прилетает и садится РОВНО в тот же слот.
    // Старт — через 2600мс после начала влияния, тот же
    // INFLUENCE_TO_TRANSFORM_GAP, что и у грамматического шага agnayas
    // (сама механика прилёта сменилась, темп причинно-следственной связи
    // — нет).
    {
      type: 'split', at: START + 3, start: 5300, label: 'yaṇ',
      holdOffset: { x: -1.6, y: 2.4, z: 0.4 },
      arrivals: [
        { into: 'r', newSlot: START + 3, from: { x: slotX(START + 3) + 1.0, y: 2.5, z: -1.5 }, delay: 500, dur: 1600, arcHeight: 0.9 },
      ],
    },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — момент завершения угасания источника:
    // 5300+900(anticipateDur)+... = 10400, см. applySplit).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
