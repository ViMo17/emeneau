// hasan + agacchat → hasannagacchat (правило 61) на слот-движке. ПЕРВЫЙ
// реальный тест гэпа DOUBLE (истинная геминация — буква удваивается САМА
// СОБОЙ, не превращается в другую) — закрывает CLAUDE.md Часть 6, п.1,
// interaction-registry.md Часть В, п.1.
//
// Правило по источнику (emeno): «После краткого простого гласного конечный
// назальный (n) удваивается перед следующим гласным». hasan «смеющийся»
// (участие, has-+-ant) + agacchat «шёл» (имперфект gam-) → hasannagacchat
// «шёл смеясь». Внешнее сандхи, но результат пишется СЛИТНО (не через
// пробел) — граница закрывается без остатка, как rule50/rule55.
//
// МЕХАНИКА (прямая правка пользователя дважды за сессию):
//   1) ДВА условия разом влияют на n: предшествующий краткий гласный
//      (a внутри hasan) И следующий гласный (a агаcchat) — оба должны
//      быть показаны, не один (иначе условие правила читается неполным).
//   2) n НЕ поднимается в отстойник (это не `split`) — новая n
//      ОТПОЧКОВЫВАЕТСЯ от исходной: зеркало `merge` (см. applyBud,
//      slot-engine-ops.js) — источник вспыхивает и остаётся на месте,
//      клон появляется ровно в его позиции и едет по прямой (не по дуге)
//      в свой слот с лёгкой пружинкой на прибытии.
//   3) Отдельного финального approach не нужно — целевой слот клона (3)
//      это ровно тот слот, что был внешним зазором между hasan и
//      agacchat: как только клон садится, слово уже слитно, зазора не
//      остаётся (в отличие от rule50/rule55, где approach закрывал ОСТАВШИЙСЯ
//      зазор отдельным шагом).
import { mountSlotExample } from '../lib/slot-engine.js';

//   0 = «has» (сжатый блок h+a+s — не участвует в самом событии, только
//       обеспечивает целое слово на экране)
//   1 = a (предшествующий краткий гласный — УСЛОВИЕ правила)
//   2 = n (источник геминации)
//   3 = (пусто — сюда «отпочкуется» вторая n; это же внешний зазор
//       hasan|agacchat, после события зазора не останется)
//   4 = a (agacchat, следующий гласный — тоже УСЛОВИЕ правила)
//   5 = g
//   6 = a
//   7 = c
//   8 = ch
//   9 = «at» (сжатый блок a+t — хвост agacchat, не участвует в событии)
export const data = {
  initial: [
    { slot: 0, tr: 'has' },
    { slot: 1, tr: 'a' },
    { slot: 2, tr: 'n' },
    { slot: 4, tr: 'a' },
    { slot: 5, tr: 'g' },
    { slot: 6, tr: 'a' },
    { slot: 7, tr: 'c' },
    { slot: 8, tr: 'ch' },
    { slot: 9, tr: 'at' },
  ],

  // Единственный шаг — само правило 61. activeSlots — оба условия (1,4),
  // сам источник (2) и будущее место клона (3).
  steps: [
    { kind: 'rule', ruleNum: 61, start: 3700, end: 8600, activeSlots: [1, 2, 3, 4], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Оба условия влияют на n РАЗОМ (два отдельных influence — та же
    // формула, что уже применена в rule50 для двух источников одной цели).
    { type: 'influence', from: 1, to: 2, start: 3700, ringHoldDur: 2500 },
    { type: 'influence', from: 4, to: 2, start: 3700, ringHoldDur: 2500 },

    // Геминация: n отпочковывает клона (тот же глиф) в слот 3 — он же
    // внешний зазор между hasan и agacchat, зазор закрывается САМИМ
    // событием, не отдельным шагом.
    { type: 'bud', from: 2, to: 3, toGlyph: 'n', start: 6200, dur: 1200, flashDecay: 600, label: 'геминация' },

    // settle не прописан — считается автоматически.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
