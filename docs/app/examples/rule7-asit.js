// āsīt (правило 7) на слот-движке — интеграционный модуль, по образцу
// rule3-agnayas-slots.js (заход 13). Данные вынесены СЮДА, а не хранятся
// дублем в test-slot-engine-rule7.html и в основном приложении — оба места
// импортируют этот файл, меняется только то, ЧТО вызывает mount().
import { mountSlotExample } from '../lib/slot-engine.js';

// āsīt: a(аугмент) + as(корень: a+s) + īt(окончание) → āsīt
// Слоты — с зазором в один слот между тремя морфологическими частями
// (А | пробел | АС | пробел | ИТ). Все пять падают вместе с самого начала —
// никто не материализуется за кадром посреди ролика. Номера подобраны так,
// чтобы центрировался ИТОГОВЫЙ результат (4 буквы после слияния), а не
// стартовая раскладка (5 букв) — см. комментарий в test-slot-engine-rule7.html.
export const data = {
  initial: [
    { slot: 1, tr: 'a' }, // аугмент — сольётся со слотом 3 на шаге 2
    { slot: 3, tr: 'a' }, // корень as-, станет ā
    { slot: 4, tr: 's' }, // корень as-, неподвижный якорь
    { slot: 6, tr: 'ī' }, // окончание, подъедет к позиции слота 5 на шаге 1
    { slot: 7, tr: 't' }, // окончание, подъедет к позиции слота 6 на шаге 1
  ],

  // Шаг 1 [Грам.]: окончание -īt присоединяется к основе — чисто
  // структурное событие, звук не меняется, поэтому притенения нет вообще
  // (activeSlots включает все слоты) — общий принцип из шаблон-документа.
  // Шаг 2 [Сандхи 7]: a+a→ā — единственное событие сандхи примера.
  steps: [
    { kind: 'grammar', start: 2700, end: 4050, activeSlots: [1, 3, 4, 6, 7] },
    // color: 0xAFBFD4 — тот же hex, что у .c1 в sanskrit-sandhi-app.html
    // (тир внутренних сандхи-гласных, к которому отнесено и правило 7,
    // g:'c1' в массиве RULES — тот же тир, что у правила 3).
    { kind: 'rule', ruleNum: 7, start: 5370, end: 7270, activeSlots: [1, 3], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // ШАГ 1: окончание -īt «примагничивается» к основе (approach,
    // retreat:false — доехал и остался, не отскочил; без несовместимости
    // и без события сандхи — тихое присоединение).
    {
      type: 'approach', movers: [6, 7], target: 4, start: 2700,
      approachDur: 1200, holdDur: 0, retreat: false,
      distance: 1.0, jitterAmp: 0, pulse: false,
    },

    // ШАГ 2: приставка-a (слот 1) едет в слот корневого a (слот 3) и
    // сливается с ним в ā — вспышка (масштаб + свечение материала) ровно
    // в момент касания.
    { type: 'merge', from: 1, at: 3, start: 5370, dur: 1400, toGlyph: 'ā' },

    // settle не прописан — считается автоматически (см. заход 8):
    // 1с после того, как последняя буква вернёт истинный цвет.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
