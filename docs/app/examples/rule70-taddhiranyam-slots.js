// tat + hiraṇyam → taddhiraṇyam (правило 70, с цепочкой в правило 71) —
// первый пример НА ДВЕ ВЕЩИ разом: цепочку из двух `rule`-шагов подряд в
// одном примере (гэп №6 шаблон-документа) и сжатые крайние блоки для
// длинных слов (гэп №13, заходы 47-49). Проверено дословно по источнику
// (Эмено, стр.22): «Звук h- после смычного меняется на звонкий
// придыхательный, соответствующий по месту произношения первому смычному
// ... tat + hiraṇyam → tat + dhiraṇyam → taddhiraṇyam» — и правило 71 прямо
// названо в тексте как применимое следом («Это правило применимо и к
// правилам 67 и 70»), не наша реконструкция.
import { mountSlotExample } from '../lib/slot-engine.js';

// tat «то» (указат. местоим. ср.р.) + hiraṇyam «золото» (сущ. ср.р.) →
// taddhiraṇyam «то золото». Внешние сандхи — граница между словами не
// схлопывается никогда, тот же принцип, что у vāk asti (rule 71).
//   2 = t ⎫
//   3 = a ⎬ tat — целиком индивидуально, слово короткое
//   4 = t ⎭ (словофинальный t — станет d на шаге 2)
//   [5 — зазор: граница между словами]
//   6 = h ⎫ hiraṇyam — h станет dh на шаге 1
//   7 = i ⎬ индивидуально, рядом с активной буквой
//   8 = «raṇyam» (сжатый блок, 6 фонем — инертный хвост, не участвует
//       ни в одном из двух шагов; авто-подгонка шрифта, заход 48)
export const data = {
  initial: [
    { slot: 2, tr: 't' },
    { slot: 3, tr: 'a' },
    { slot: 4, tr: 't' },
    { slot: 6, tr: 'h' },
    { slot: 7, tr: 'i' },
    { slot: 8, tr: 'raṇyam' },
  ],

  // ДВА `rule`-шага подряд — первый реальный пример цепочки правил в
  // слот-движке. Оба шага — один и тот же активный участок (4 и 6),
  // просто роли триггер/цель меняются местами: на шаге 1 T(4) воздействует
  // на H(6); на шаге 2 уже DH(6, результат шага 1) воздействует на T(4).
  steps: [
    { kind: 'rule', ruleNum: 70, start: 2900, end: 7050, activeSlots: [4, 6], color: 0xAE987A, primary: true },
    { kind: 'rule', ruleNum: 71, start: 7300, end: 10750, activeSlots: [4, 6], color: 0xAE987A, primary: true },
  ],

  ops: [
    // ШАГ 1 (правило 70): h→dh, вызвано предшествующим t (место образования
    // результата — от НЕГО, не от исходного h, у которого единого места
    // образования нет вообще, COL_DIM). НЕ парная замена внутри варги
    // (h не входит ни в одну варгу) — обычный transform, 360°, нейтральная
    // грань (не серебро — не гунация).
    { type: 'influence', from: 4, to: 6, start: 2900, ringHoldDur: 4000 },
    { type: 'transform', at: 6, toGlyph: 'dh', start: 5500, spinTurns: 1, signal: 'blank' },

    // ШАГ 2 (правило 71): t→d, вызвано уже готовым dh (результатом шага 1).
    // Та же самая механика, что уже отлажена на vāk asti (k→g) — парная
    // замена внутри варги (глухая↔звонкая), 180°, нейтральная грань.
    { type: 'influence', from: 6, to: 4, start: 7300, ringHoldDur: 3300 },
    { type: 'transform', at: 4, toGlyph: 'd', start: 9900, spinTurns: 0.5, signal: 'blank' },

    // settle не прописан — считается автоматически (см. заход 8):
    // 1с после того, как последняя буква вернёт истинный цвет.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
