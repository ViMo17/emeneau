// tat + hiraṇyam → taddhiraṇyam (правило 70, с цепочкой в правило 71) —
// первый пример НА ДВЕ ВЕЩИ разом: цепочку из двух `rule`-шагов подряд в
// одном примере (гэп №6 шаблон-документа) и сжатые крайние блоки для
// длинных слов (гэп №13, заходы 47-49). Проверено дословно по источнику
// (Эмено, стр.22): «Звук h- после смычного меняется на звонкий
// придыхательный, соответствующий по месту произношения первому смычному
// ... tat + hiraṇyam → tat + dhiraṇyam → taddhiraṇyam» — и правило 71 прямо
// названо в тексте как применимое следом («Это правило применимо и к
// правилам 67 и 70»), не наша реконструкция.
//
// ИСПРАВЛЕНО (заход 51, по прямой правке после первого показа):
//   1) Сжатие уменьшено с 6 букв («raṇyam») до 3 («yam») — таков был
//      исходный уговор (3 буквы, искл. только правило 62 — 4). Раньше
//      использовала 6 без спроса — превышение лимита, не согласованное.
//      Задействованы теперь ВСЕ 10 слотов (r, a, ṇ — индивидуально), не 7.
//   2) DH (шаг 1) раскачивается ВЛЕВО при повороте (clearance:-0.35) — при
//      бывшей раскладке разворот вправо (дефолт) наезжал на текстуру
//      соседнего кубика I. Слева теперь зазор (пусто) — безопасно.
//   3) Шаг 2 (правило 71, вспомогательное в цепочке) — БЕЗ primary:true.
//      Цвет вспомогательных шагов стандартизирован отдельно (заход 51,
//      slot-engine.js) — переиспользует уже существующий охровый тон
//      грамматики, не новый цвет.
