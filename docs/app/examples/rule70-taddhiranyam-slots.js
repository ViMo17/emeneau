// tat «то» (указат. местоим. ср.р.) + hiraṇyam «золото» (сущ. ср.р.) →
// taddhiraṇyam «то золото». Внешние сандхи — граница между словами не
// схлопывается никогда, тот же принцип, что у vāk asti (rule 71).
//   0 = t ⎫
//   1 = a ⎬ tat — целиком индивидуально
//   2 = t ⎭ (словофинальный t — станет d на шаге 2)
//   [3 — зазор: граница между словами]
//   4 = h ⎫
//   5 = i │
//   6 = r ⎬ hiraṇyam — h станет dh на шаге 1; r,a,ṇ индивидуально, до
//   7 = a │ конца лимита в 3 буквы на сжатый блок
//   8 = ṇ ⎭
//   9 = «yam» (сжатый блок, РОВНО 3 фонемы — лимит соблюдён)
