// vāk asti → vāg asti (правило 71) на слот-движке — перенесено со старого
// рукописного модуля (docs/app/examples/rule71-vak-asti.js, НЕ удалён,
// остаётся эталоном) на канонические техники слот-движка, по реестру
// эталонных эффектов (CLAUDE.md, Часть 4):
//   - transform: 360°×spinTurns + рантайм-перерисовка текстуры (было —
//     180° + заранее заготовленные двусторонние грани);
//   - influence: текстурный пульс на источнике (было — то же самое по
//     сути, эталон и был источником этой техники — здесь она просто через
//     общий движковый setFacePulse/redrawPulseFace, не через отдельную
//     копию кода внутри примера).
// ПЕРВЫЙ пример ВНЕШНИХ сандхи в слот-движке: два отдельных слова, граница
// между ними НЕ схлопывается никогда (в отличие от agnayas/āsīt/śādhi —
// там всегда получается одно слитное слово). Здесь это получается само
// собой: между vāk и asti — зазор в один слот, и ни одна операция его не
// трогает (k меняется НА МЕСТЕ, никто никуда не едет) — граница остаётся
// зазором на всём протяжении примера, включая финал.
import { mountSlotExample, TRANSFORM_KIND } from '../lib/slot-engine.js';

// vāk «речь, голос» (им. п. ед. ч. основы vāc-, k — из c по правилам
// сандхи основы) + asti «есть, существует» (3 л. ед. ч. наст. вр. от
// as-). k — глухой, перед следующим звонким a (гласные всегда звонкие)
// озвончается: k→g. Правило внешних сандхи, «прямое» — как и śādhi,
// никакой грамматической подготовки не требуется, единственный шаг —
// сама сандхи.
//   1 = v  ⎫
//   2 = ā  ⎬ vāk — первое слово
//   3 = k  ⎭ (sthānin — станет g)
//   [4 — зазор: граница между словами, не схлопывается никогда]
//   5 = a  ⎫ (nimitta — причина озвончения)
//   6 = s  │
//   7 = t  ⎬ asti — второе слово
//   8 = i  ⎭
export const data = {
  initial: [
    { slot: 1, tr: 'v' },
    { slot: 2, tr: 'ā' },
    { slot: 3, tr: 'k' },
    { slot: 5, tr: 'a' },
    { slot: 6, tr: 's' },
    { slot: 7, tr: 't' },
    { slot: 8, tr: 'i' },
  ],

  // Единственный шаг — сама сандхи. activeSlots — k и a, единственные
  // участники события (озвончение вызвано конкретно следующим гласным,
  // не всем словом asti целиком); v, ā, s, t, i — контекст, притенены.
  steps: [
    // color: 0xAE987A — тот же hex, что у .eg-chip.c5 в sanskrit-sandhi-app.css
    // (тир 50–71, персиковый) — сверено перед интеграцией в EXAMPLES[71].
    { kind: 'rule', ruleNum: 71, start: 3200, end: 6650, activeSlots: [3, 5], color: 0xAE987A, primary: true },
  ],

  ops: [
    // Влияние a→k: непрерывный текстурный пульс на a (единственный
    // источник, не группа — озвончение вызвано конкретно следующим
    // гласным, не всем словом целиком) + бегущие волны a→k. ringHoldDur
    // продлевает пульс до конца transform (см. ниже) — источник «не
    // отпускает», пока превращение не завершится, тот же приём, что у
    // agnayas.
    { type: 'influence', from: 5, to: 3, start: 3200, ringHoldDur: 3300 },

    // Само превращение: k→g, НА МЕСТЕ (никто никуда не едет — внешние
    // сандхи здесь не схлопывают границу слов). Цвет не переопределён —
    // colorFor('g') и так даёт тот же гортанный тон, что у k (озвончение
    // не меняет место образования, только звонкость). signal:'blank' —
    // ОБЯЗАТЕЛЬНО, не дефолт: серебро (дефолт, matsSignal) зарезервировано
    // за гунацией/вриддхи (см. CLAUDE.md, Часть 3 — реестр эталонных
    // эффектов) — здесь другая категория, парная звонкая замена внутри
    // варги, не имеет отношения к огласовке корня. spinTurns:0.5, НЕ 1 —
    // 0.5×360°=180° — ПРОТИВОЛЕЖАЩАЯ грань кубика, геометрически
    // материализованная «пара»: категория меняет саму цифру оборота, не
    // только цвет. Шкала закреплена в реестре: 0.5=180° парная замена,
    // 1=360° гуна, 2=720° вриддхи.
    { type: 'transform', at: 3, toGlyph: 'g', start: 5800, ...TRANSFORM_KIND.vargaPair, label: 'jaśtva' },

    // settle не прописан — считается автоматически: 1с после того, как
    // последняя буква вернёт истинный цвет.
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
