// bharant- + s → bharan «несущий» — СОБСТВЕННЫЙ (родной) пример Эменó/
// Уитни для правила 9 самого по себе (дословно из emeno: «bharant- + s →
// bharan»), не suhārt — тот в EXAMPLES[9] помечен `annotated:true`
// (дополнительная иллюстрация, взятая из цитаты правила 8, не родная для
// правила 9). Построен по прямому требованию пользователя: «мы обязались
// сделать кликабельным 1й пример из каждого правила» — suhārt был вторым
// элементом массива, а не первым, поэтому первым должен стать РОДНОЙ
// пример, оживлённый в 3D, а не 2D-заглушка.
//
// РАЗБОР ФОРМЫ. bharant- «несущий» — наст. действ. причастие (атематический
// суффикс -ant/-at) корня bhṛ- «нести» (класс III, реduplицирующий,
// либо непосредственно от корня — само причастие образуется от основы
// наст. времени + -ant). Окончание им. п. ед. ч. -s (корневой тип
// склонения, присоединяется прямо к основе): bharant+s.
//
// ПРАВИЛО 9 (Whitney §150, сверено дословно по Wikisource; Pāṇini 8.2.23
// saṃyogāntasya lopaḥ, «конечный элемент [словофинального] скопления
// согласных исчезает») — Уитни формулирует правило ИТЕРАТИВНО: «if two or
// more [consonants] would etymologically occur [at the end of a word], the
// last is dropped, and again the last». На конце bharant+s оказывается
// СКОПЛЕНИЕ ИЗ ТРЁХ согласных (n-t-s):
//  1. ПЕРВАЯ итерация — отпадает ПОСЛЕДНИЙ элемент, суффиксальное -s:
//     bharants → bharant.
//  2. На конце ВСЁ ЕЩЁ скопление из двух согласных (-nt) — правило
//     применяется ПОВТОРНО, той же формулой: отпадает t → bharan.
//  3. Итог: bharan — уцелевший согласный (n) ВСЕГДА первый из исходного
//     скопления, не произвольный.
// В отличие от suhārt (где вторая итерация БЛОКИРУЕТСЯ правилом 8 —
// корневой d после r), здесь ОБА отсечения проходят без исключений — это
// самый чистый, беспримесный пример именно правила 9 как такового.
// Оба elide — ПОЛНЫЙ драматичный эффект (не quiet), не побочный спутник
// чего-то ещё: это и есть всё содержание правила.
//
// ПОЛОЖЕНИЕ В АБСОЛЮТНОМ ИСХОДЕ (padânta) — уточнение, найденное при
// сверке. §150 у Уитни физически стоит в ТОМ ЖЕ разделе «изменения на
// конце слова», что и висарга (конечное -s/-r → придыхание перед паузой)
// — Pāṇini относит его к adhikāra «padasya» (8.1.16): правило описывает
// абсолютно словофинальное состояние (изолированную/цитатную форму
// слова), ту же границу, что уже отмечена данной («।», avasāna) у
// suhārt. Добавлена ТА ЖЕ данда — присутствует С САМОГО НАЧАЛА (падает
// вместе со всеми буквами, граница не «наступает», она есть всегда) —
// и служит физическим источником `influence` ДЛЯ ОБЕИХ итераций разом
// (Уитни сам говорит «the last is dropped, AND AGAIN THE LAST» — обе
// итерации показаны ОДНИМ и тем же визуальным приёмом).
// **ОГОВОРКА, ЧЕСТНО ОТМЕЧЕННАЯ ЗВЁЗДОЧКОЙ** (`label:'lopa*'`, та же
// дисциплина, что и у suhārt) — ПЕРЕПРОВЕРЕНО повторно (прямой вопрос
// пользователя): правило 9 (padânta) — БЕЗУСЛОВНОЕ, не зависит от того,
// что следует дальше (гласный/согласный/пауза начала следующего слова) —
// то же сокращение произошло бы, даже если bharant+s стояло бы перед
// гласным. avasāna здесь НЕ является настоящей причиной вообще — данда
// ЧИСТО ВИЗУАЛЬНЫЙ ПРИЁМ, дающий физическое присутствие иначе невидимому
// условию «конец слова» (иначе нечем показать, почему событие происходит
// именно сейчас), не заявление, что пауза буквально ВЫЗЫВАЕТ отсечение —
// в отличие от правила 31 (vāvasāne, где пауза ПОДЛИННОЕ условие,
// названное самой сутрой Панини 8.4.56).
import { mountSlotExample, centeredStart } from '../lib/slot-engine.js';

// Раскладка центрирована по НАЧАЛЬНОЙ 8-тайловой раскладке (не по
// итоговой 6-тайловой) — прямая правка по живой проверке пользователем:
// centeredStart(6)=2 давало идеально центрированный ИТОГ, но начальные
// 8 тайлов (bh..s+данда) при этом занимали слоты 2..9 — упирались в
// правый край стенда, визуально «съехав вправо» на всё время, пока идут
// обе итерации (дольше, чем держится сам финальный кадр). centeredStart(8)
// балансирует начальную раскладку (слоты 1..8, оба края равноудалены от
// центра), но сдвигает ИТОГОВЫЙ результат (bharan+данда, 6 тайлов) на
// 1 слот левее истинного центра — единственная альтернатива при целых
// слотах (centeredStart(8)=1 и centeredStart(6)=2 различаются РОВНО на 1,
// в отличие от suhārt, где обе формулы случайно совпадали). bh/a/r/a/n НЕ
// двигаются вообще — стоят на одном и том же месте от начала до конца.
const START = centeredStart(8); // = 1
//   START+0 = bh ⎫
//   START+1 = a  │
//   START+2 = r  ⎬ bharant- — атематическое действ. причастие корня bhṛ-
//   START+3 = a  │ «нести» (уцелевшая часть, остаётся после обоих шагов)
//   START+4 = n  ⎭
//   START+5 = t    — конечный согласный основы (отпадёт шагом 2)
//   START+6 = s    — окончание Nom.sg. (суффиксальное, отпадёт шагом 1)
//   START+7 = ।    — avasāna (пауза), присутствует с самого начала,
//                    после обоих отсечений придвигается на слот n+1
export const data = {
  initial: [
    { slot: START + 0, tr: 'bh' },
    { slot: START + 1, tr: 'a' },
    { slot: START + 2, tr: 'r' },
    { slot: START + 3, tr: 'a' },
    { slot: START + 4, tr: 'n' },
    { slot: START + 5, tr: 't' },
    { slot: START + 6, tr: 's' },
    { slot: START + 7, tr: '।' },
  ],

  steps: [
    // Шаг «правило 9», ПЕРВАЯ итерация: отсекается суффиксальное -s.
    // activeSlots включает данду — источник причины (padânta), не только
    // саму цель.
    { kind: 'rule', ruleNum: 9, start: 3220, end: 9220, activeSlots: [START + 6, START + 7], color: 0xAFBFD4, primary: true },
    // Шаг «правило 9», ВТОРАЯ итерация — ТА ЖЕ формула применяется
    // ПОВТОРНО к новому конечному согласному (t), ТОЙ ЖЕ причиной
    // (данда). Оба шага — один и тот же номер правила, сознательно (не
    // разные правила) — сама повторность и есть содержание итеративной
    // формулировки Уитни. Держится активным до конца финального approach
    // данды (тот же приём, что у rule55 — шаг остаётся активным, пока
    // его участник физически не займёт итоговое место).
    { kind: 'rule', ruleNum: 9, start: 9220, end: 16420, activeSlots: [START + 5, START + 7], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // ПРИЧИНА первой итерации: данда (avasāna) пульсирует К s — та же
    // техника, что у suhārt (данда→s). ringHoldDur:3900 — пульс
    // продолжается ещё 1300мс после начала elide, не обрывается ровно в
    // момент реакции.
    { type: 'influence', from: START + 7, to: START + 6, start: 3220, ringHoldDur: 3900 },

    // Первая итерация: суффиксальное -s исчезает без следа — полный lopa
    // (не quiet — само содержание события). label:'lopa*' — звёздочка,
    // та же честная оговорка, что у suhārt (см. комментарий выше файла).
    // Пауза чистой пульсации перед реакцией — 2600мс (3220+2600=5820).
    // Готово (cube.mesh удалён) на 5820+riseDur(1300)+holdDur(800)+
    // fadeDur(1100) = 5820+3200 = 9020.
    { type: 'elide', at: START + 6, start: 5820, label: 'lopa*' },

    // ПРИЧИНА второй итерации: ТА ЖЕ данда, теперь пульсирует К t (новому
    // конечному согласному после отпадения s) — 200мс буфер после того,
    // как -s реально исчез (9020+200=9220). Не смежные слоты в этот
    // момент (между t и данной — пустой слот бывшего s), но influence не
    // требует физического соседства (см. CLAUDE.md, гэп DISTANT).
    { type: 'influence', from: START + 7, to: START + 5, start: 9220, ringHoldDur: 3900 },

    // Вторая итерация: та же формула применяется повторно к t, тоже
    // полный lopa*. Пауза чистой пульсации — 2600мс (9220+2600=11820).
    // Готово на 11820+3200 = 15020.
    { type: 'elide', at: START + 5, start: 11820, label: 'lopa*' },

    // Данда придвигается на освободившееся место (2 слота — бывшие t и s
    // оба пусты) — закрывает зазор, тот же приём, что и в rule55/suhārt,
    // просто на большую дистанцию. 200мс буфер после того, как вторая
    // итерация реально завершилась (15020+200=15220). retreat:false/
    // holdDur:0 — доехала и осталась на месте.
    { type: 'approach', movers: [START + 7], target: START + 5, start: 15220, approachDur: 1200, holdDur: 0, retreat: false, distance: 2.0, jitterAmp: 0, pulse: false },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — совпадает с моментом завершения approach,
    // 15220+1200=16420).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
