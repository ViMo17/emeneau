// bharant- + s → bharan «несущий» — СОБСТВЕННЫЙ (родной) пример Эменó/
// Уитни для правила 9 самого по себе (дословно из emeno: «bharant- + s →
// bharan»), не suhārt — тот в EXAMPLES[9] помечен `annotated:true`
// (дополнительная иллюстрация, взятая из цитаты правила 8, не родная для
// правила 9). Построен по прямому требованию пользователя: «мы обязались
// сделать кликабельным 1й пример из каждого правила» — suhārt был вторым
// элементом массива, а не первым, поэтому первым должен стать РОДНОЙ
// пример, оживлённый в 3D, а не 2D-заглушка.
//
// РАЗБОР ФОРМЫ. bharant- «несущий» — наст. действ. причастие (атематический
// суффикс -ant/-at) корня bhṛ- «нести» (класс III, реduplицирующий,
// либо непосредственно от корня — само причастие образуется от основы
// наст. времени + -ant). Окончание им. п. ед. ч. -s (корневой тип
// склонения, присоединяется прямо к основе): bharant+s.
//
// ПРАВИЛО 9 (Whitney §150, сверено дословно по Wikisource; Pāṇini 8.2.23
// saṃyogāntasya lopaḥ, «конечный элемент [словофинального] скопления
// согласных исчезает») — Уитни формулирует правило ИТЕРАТИВНО: «if two or
// more [consonants] would etymologically occur [at the end of a word], the
// last is dropped, and again the last». На конце bharant+s оказывается
// СКОПЛЕНИЕ ИЗ ТРЁХ согласных (n-t-s):
//  1. ПЕРВАЯ итерация — отпадает ПОСЛЕДНИЙ элемент, суффиксальное -s:
//     bharants → bharant.
//  2. На конце ВСЁ ЕЩЁ скопление из двух согласных (-nt) — правило
//     применяется ПОВТОРНО, той же формулой: отпадает t → bharan.
//  3. Итог: bharan — уцелевший согласный (n) ВСЕГДА первый из исходного
//     скопления, не произвольный.
// В отличие от suhārt (где вторая итерация БЛОКИРУЕТСЯ правилом 8 —
// корневой d после r), здесь ОБА отсечения проходят без исключений — это
// самый чистый, беспримесный пример именно правила 9 как такового.
// Оба elide — ПОЛНЫЙ драматичный эффект (не quiet), не побочный спутник
// чего-то ещё: это и есть всё содержание правила. label:'lopa' БЕЗ
// звёздочки — здесь, в отличие от suhārt, никакой причинно-следственной
// связи с avasāna не заявляется, только сам факт исчезновения.
import { mountSlotExample, centeredStart } from '../lib/slot-engine.js';

// Раскладка центрирована по ИТОГОВОМУ 5-фонемному результату «bharan»
// (bh-a-r-a-n) — centeredStart(5)=2, тот же принцип, что и у rule42/
// suhārt: финальное состояние держит внимание зрителя дольше всего.
const START = centeredStart(5); // = 2
//   START+0 = bh ⎫
//   START+1 = a  │
//   START+2 = r  ⎬ bharant- — атематическое действ. причастие корня bhṛ-
//   START+3 = a  │ «нести» (уцелевшая часть, остаётся после обоих шагов)
//   START+4 = n  ⎭
//   START+5 = t    — конечный согласный основы (отпадёт шагом 2)
//   START+6 = s    — окончание Nom.sg. (суффиксальное, отпадёт шагом 1)
export const data = {
  initial: [
    { slot: START + 0, tr: 'bh' },
    { slot: START + 1, tr: 'a' },
    { slot: START + 2, tr: 'r' },
    { slot: START + 3, tr: 'a' },
    { slot: START + 4, tr: 'n' },
    { slot: START + 5, tr: 't' },
    { slot: START + 6, tr: 's' },
  ],

  steps: [
    // Шаг «правило 9», ПЕРВАЯ итерация: отсекается суффиксальное -s.
    { kind: 'rule', ruleNum: 9, start: 3220, end: 6620, activeSlots: [START + 6], color: 0xAFBFD4, primary: true },
    // Шаг «правило 9», ВТОРАЯ итерация — ТА ЖЕ формула применяется
    // ПОВТОРНО к новому конечному согласному (t). Оба шага — один и тот
    // же номер правила, сознательно (не разные правила) — сама
    // повторность и есть содержание итеративной формулировки Уитни.
    { kind: 'rule', ruleNum: 9, start: 6620, end: 9820, activeSlots: [START + 5], color: 0xAFBFD4, primary: true },
  ],

  ops: [
    // Первая итерация: суффиксальное -s исчезает без следа — полный lopa.
    // Готово (cube.mesh удалён) на 3220+riseDur(1300)+holdDur(800)+
    // fadeDur(1100) = 3220+3200 = 6420.
    { type: 'elide', at: START + 6, start: 3220, label: 'lopa' },

    // Вторая итерация: 200мс буфер после того, как -s реально исчез
    // (6420) — та же формула применяется повторно к t, тоже полный lopa
    // (не quiet — это тоже само содержание правила, не побочный эффект).
    // Готово на 6620+3200 = 9820.
    { type: 'elide', at: START + 5, start: 6620, label: 'lopa' },

    // settle не прописан — считается автоматически, от step.end выше
    // (плотно, без запаса — совпадает с моментом завершения второго elide).
  ],
};

export function mount(container) {
  return mountSlotExample(container, data);
}
