// su-hārd- + -s → suhārt (перед паузой, avasāna) — правила 8/9/31 на
// слот-движке, все три на одном слове. ОБЩАЯ, разделяемая библиотека
// данных+механики (файл переименован из rule31-suhart-slots.js при
// интеграции — раньше был «файлом правила 31», хотя всегда покрывал все
// три правила; теперь это явно нейтральное имя) — реальные точки входа
// приложения — три ТОНКИХ файла-обёртки, каждый со своим `targetRuleNum`:
// `rule8-suhart-slots.js`, `rule9-suhart-slots.js`, `rule31-suhart-slots.js`.
// Этот файл продолжает использоваться напрямую тестовым полигоном
// (`test-slot-engine-rule31.html`, без targetRuleNum — все три шага
// показываются крупными разом, для полного обзора всех трёх правил).
//
// РАЗБОР ФОРМЫ. suhārd- «друг» (su- «хороший» + hārda- «сердечный»,
// бахуврихи, «имеющий доброе сердце») — согласнoосновное сущ. муж. рода
// (корневой тип склонения, основа оканчивается прямо на согласный d, без
// тематического гласного). Им.п.ед.ч. строится присоединением окончания
// -s прямо к основе: suhārd+s.
//
// ПОЛНАЯ ЦЕПОЧКА ИЗ ТРЁХ ПРАВИЛ (Уитни §150/§150b/§141/§159, сверено
// дословно по Wikisource) — ВСЕ ТРИ АНИМИРОВАНЫ КАК ОТДЕЛЬНЫЕ ШАГИ (прямая
// правка пользователя, второй пересмотр: «введи шаг 3 — правило 8» — раз
// все кубики понятны, недостаточно показать исключение ЧИСТЫМ КОНТРАСТОМ
// [d просто не дим, пока s исчезает] — нужен собственный, видимый МОМЕНТ
// самой попытки и её провала). Уитни сам формулирует правило 9 (§150)
// ИТЕРАТИВНО — «the last is dropped, AND AGAIN THE LAST» — это НАПРЯМУЮ
// подсказывает трёхшаговую драматургию: первая итерация снимает суффиксальное
// -s, вторая итерация «пытается» снять теперь уже конечный d — и именно
// эта вторая попытка блокируется правилом 8:
//  1. Правило 9, ПЕРВАЯ итерация (W150) — конечное скопление согласных
//     «r-d-s» сокращается с конца: суффиксальное -s (окончание Nom.sg.)
//     РЕАЛЬНО ОТСЕКАЕТСЯ. `elide` (label:'lopa') — первое применение
//     самого правила 9 в 3D вообще.
//  2. Правило 8, ВТОРАЯ (БЛОКИРОВАННАЯ) итерация (W150b, ИСКЛЮЧЕНИЕ из
//     правила 9) — «a non-nasal mute, if radical and not suffixal, is
//     retained after r»: d теперь тоже конечный, по общей логике
//     правила 9 мог бы отсечься тоже — но d КОРНЕВОЙ (часть hārda-, не
//     окончание), стоит ПОСЛЕ r → правило 8 НЕ ДАЁТ ему уйти. Уитни
//     приводит ИМЕННО ЭТОТ пример дословно: «suhā́rt from suhārd»
//     (§150b). r — ИМЕННО ТОТ маркер условия, из-за которого правило
//     срабатывает (не «просто соседняя буква» — прямая формулировка
//     самой сутры называет позицию «после r»), поэтому r получает
//     СОБСТВЕННЫЙ `influence`-пульс К d ПЕРЕД попыткой (та же техника,
//     что уже даёт причину cartva на шаге 3 и lopa на шаге 1 — здесь
//     источник не данда, а r, физически соседняя буква корня). Только
//     ПОСЛЕ этого d буквально начинает уходить вниз ТЕМ ЖЕ движением,
//     что и elide (новая операция `resist`, см. slot-engine-ops.js), но
//     не долетает: коротко зависает и пружинисто отскакивает обратно на
//     место, НЕ исчезая. Одновременно весь корень hārda- (h-ā-r-d)
//     подчёркнут общей нейтральной рамкой (`groupSlots`, GROUP_COLOR) —
//     зритель видит ДВА дополняющих факта разом: (а) КОНКРЕТНО r —
//     позиционное условие (собственный `influence`), (б) корень ЦЕЛИКОМ
//     защищён как неделимое целое (рамка) — точно соответствует двум
//     частям формулировки Уитни («after r» + «if radical»), не одно
//     вместо другого. У правила 8 по-прежнему нет собственного
//     ЗВУКОВОГО перехода (`toGlyph` не меняется) и нет пилюли-термина —
//     это демонстрация ИСКЛЮЧЕНИЯ (блокировки), не сандхи-механики с
//     устоявшимся санскритским названием, изобретать термин не по чему.
//  3. Правило 31 (W141, W159; Pāṇini 8.4.54–56 abhyāse carca / khari ca /
//     vāvasāne — традиционный термин cartva, चर्त्व) — звонкий смычный d,
//     оказавшийся ПЕРЕД ПАУЗОЙ (концом произнесения, avasāna), не может
//     оставаться звонким — оглушается в своего партнёра по той же варге,
//     t. Показано через `influence`+`transform` — единственная реальная
//     анимируемая сандхи-замена звука на этом слове.
//
// МАРКЕР ПАУЗЫ (`avasāna`, «।», U+0964 DEVANAGARI DANDA) — НОВАЯ,
// СОЗНАТЕЛЬНАЯ ОГОВОРЕННАЯ ОГОВОРКА к принципу «один кубик = одна
