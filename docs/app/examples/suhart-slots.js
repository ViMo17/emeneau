// opts.targetRuleNum (8, 9 или 31) — необязательный: если задан, только
// шаг с этим ruleNum получает primary:true (крупный чип), остальные два —
// primary:false (стандартный вспомогательный охровый is-grammar). Без
// параметра — все три primary:true, как всегда было (см. комментарий
// выше файла, «РАЗМЕР ПИЛЮЛЬ ШАГОВ ПО ЦЕЛЕВОМУ ПРАВИЛУ»).
export function mount(container, opts) {
  const targetRuleNum = opts?.targetRuleNum;
  const exampleData = targetRuleNum == null ? data : {
    ...data,
    steps: data.steps.map(s => ({ ...s, primary: s.ruleNum === targetRuleNum })),
  };
  return mountSlotExample(container, exampleData);
}
