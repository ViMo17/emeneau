// su-hārd- + -s → suhārt (перед паузой, avasāna) — правила 8/9/31 на
// слот-движке, все три на одном слове. ОБЩАЯ, разделяемая библиотека
// данных+механики (файл переименован из rule31-suhart-slots.js при
// интеграции — раньше был «файлом правила 31», хотя всегда покрывал все
// три правила; теперь это явно нейтральное имя) — реальные точки входа
// приложения — три ТОНКИХ файла-обёртки, каждый со своим `targetRuleNum`:
// `rule8-suhart-slots.js`, `rule9-suhart-slots.js`, `rule31-suhart-slots.js`.
// Этот файл продолжает использоваться напрямую тестовым полигоном
// (`test-slot-engine-rule31.html`, без targetRuleNum — все три шага
// показываются крупными разом, для полного обзора всех трёх правил).
//
// РАЗБОР ФОРМЫ. suhārd- «друг» (su- «хороший» + hārda- «сердечный»,
// бахуврихи, «имеющий доброе сердце») — согласнoосновное сущ. муж. рода
// (корневой тип склонения, основа оканчивается прямо на согласный d, без
// тематического гласного). Им.п.ед.ч. строится присоединением окончания
// -s прямо к основе: suhārd+s.
//
// ПОЛНАЯ ЦЕПОЧКА ИЗ ТРЁХ ПРАВИЛ (Уитни §150/§150b/§141/§159, сверено
// дословно по Wikisource) — ВСЕ ТРИ АНИМИРОВАНЫ КАК ОТДЕЛЬНЫЕ ШАГИ (прямая
// правка пользователя, второй пересмотр: «введи шаг 3 — правило 8» — раз
// все кубики понятны, недостаточно показать исключение ЧИСТЫМ КОНТРАСТОМ
// [d просто не дим, пока s исчезает] — нужен собственный, видимый МОМЕНТ
// самой попытки и её провала). Уитни сам формулирует правило 9 (§150)
// ИТЕРАТИВНО — «the last is dropped, AND AGAIN THE LAST» — это НАПРЯМУЮ
// подсказывает трёхшаговую драматургию: первая итерация снимает суффиксальное
// -s, вторая итерация «пытается» снять теперь уже конечный d — и именно
// эта вторая попытка блокируется правилом 8:
//  1. Правило 9, ПЕРВАЯ итерация (W150) — конечное скопление согласных
//     «r-d-s» сокращается с конца: суффиксальное -s (окончание Nom.sg.)
//     РЕАЛЬНО ОТСЕКАЕТСЯ. `elide` (label:'lopa') — первое применение
//     самого правила 9 в 3D вообще.
//  2. Правило 8, ВТОРАЯ (БЛОКИРОВАННАЯ) итерация (W150b, ИСКЛЮЧЕНИЕ из
//     правила 9) — «a non-nasal mute, if radical and not suffixal, is
//     retained after r»: d теперь тоже конечный, по общей логике
//     правила 9 мог бы отсечься тоже — но d КОРНЕВОЙ (часть hārda-, не
//     окончание), стоит после r → правило 8 НЕ ДАЁТ ему уйти. Уитни
//     приводит ИМЕННО ЭТОТ пример дословно: «suhā́rt from suhārd»
//     (§150b). Показано НОВОЙ операцией движка `resist` (см.
//     slot-engine-ops.js) — d буквально начинает уходить вниз ТЕМ ЖЕ
//     движением, что и elide, но не долетает: коротко зависает и
//     пружинисто отскакивает обратно на место, НЕ исчезая. Одновременно
//     весь корень hārda- (h-ā-r-d) подчёркнут общей нейтральной рамкой
//     (`groupSlots`, GROUP_COLOR) — зритель видит, что защищён не
//     отдельно d, а КОРЕНЬ КАК НЕДЕЛИМОЕ ЦЕЛОЕ, ту же визуальную рамку,
//     что уже несёт этот смысл у многоисточникового `influence`. У
//     правила 8 по-прежнему нет собственного ЗВУКОВОГО перехода
//     (`toGlyph` не меняется) и нет пилюли-термина — это демонстрация
//     ИСКЛЮЧЕНИЯ (блокировки), не сандхи-механики с устоявшимся
//     санскритским названием, изобретать термин не по чему.
//  3. Правило 31 (W141, W159; Pāṇini 8.4.54–56 abhyāse carca / khari ca /
//     vāvasāne — традиционный термин cartva, चर्त्व) — звонкий смычный d,
//     оказавшийся ПЕРЕД ПАУЗОЙ (концом произнесения, avasāna), не может
//     оставаться звонким — оглушается в своего партнёра по той же варге,
//     t. Показано через `influence`+`transform` — единственная реальная
//     анимируемая сандхи-замена звука на этом слове.
//
// МАРКЕР ПАУЗЫ (`avasāna`, «।», U+0964 DEVANAGARI DANDA) — НОВАЯ,
// СОЗНАТЕЛЬНАЯ ОГОВОРЕННАЯ ОГОВОРКА к принципу «один кубик = одна
// фонема» (Часть 3 CLAUDE.md): у события правила 31 НЕТ физического
// соседа-причины — триггер ПОЗИЦИОННЫЙ (конец слова перед паузой), и без
// зримого источника `influence` не может показать, ОТКУДА идёт причина
// (та же проблема уже отмечена для правила 13, 2D-only). Решение — прямая
// правка пользователя: данда («।») — не орфографический разделитель ФРАЗ
// вообще (как могло бы показаться), а ТОЧНО тот случай — Pāṇini сам
// определяет avasāna как «пауза» (1.4.110 avasānaṃ viramaḥ) именно на
// границе высказывания/его значимой части, где danda и ставится на
// письме — санскритская традиция уже связывает эти два понятия, не
// изобретаем связь заново. Кубик с данной как `tr` НЕ фонема — `colorFor`
// уже штатно даёт ему нейтральный `COL_DIM` без единой новой строчки
// движка (тот же путь, что уже проверен на аваграхе, rule50, «'», W175a).
// Присутствует С САМОГО НАЧАЛА (падает вместе со всеми буквами) — пауза
// не «наступает», она есть всегда как граница высказывания, к которой
// прижимается конец слова; после того как -s (шаг 1) освобождает слот
// перед ней, данда физически придвигается (`approach`, закрывает зазор
// на 1 слот — тот же приём, что и закрытие зазора после elide в rule55),
// и лишь потом становится источником `influence` для cartva.
//
// ГЕОМЕТРИЯ ВРАЩЕНИЯ: после того как данда придвинулась, у d ОБА соседа
// заняты (r слева, данда справа, без единого зазора) — та же ситуация,
// что уже дважды встречалась (rule2, rule6): `clearance:0` (раскачивания
// вбок нет, некуда), `clearanceZ:-0.5` (выдвижение от камеры спасает от
// прохождения сквозь текстуру соседей на диагоналях вращения).
//
// ПРИЧИНА ДЛЯ ШАГА 1 (прямая правка пользователя: «непонятно, почему
// уходит S» — событие начиналось резко, без видимого источника причины,
// в отличие от шагов 2/3, у которых есть явный визуальный сигнал).
// Добавлен `influence` ОТ ДАНДЫ (avasāna) К s ПЕРЕД elide — та же
// техника, что уже даёт причину cartva на шаге 3 (данда как источник),
// применена и здесь: сокращение конечного скопления согласных (правило 9)
// происходит ИМЕННО потому, что слово стоит перед паузой — та же причина,
// что управляет и правилом 31 (vāvasāne). **ОГОВОРКА, ЧЕСТНО ОТМЕЧЕННАЯ
// ЗВЁЗДОЧКОЙ НА ПИЛЮЛЕ** (`label:'lopa*'`, не просто `'lopa'`) — Эменó
// формулирует правило 9 (и Уитни, §150) как общий фонотактический закон,
// без явной привязки к avasāna конкретно (в отличие от правила 31, где
// Pāṇini сам называет vāvasāne) — связь «пауза вызывает и это сокращение
// тоже» лингвистически обоснована (словофинальные скопления
// действительно упрощаются именно в позиции перед паузой), но это НАША
// синтезированная демонстрация, не дословная формулировка источника.
// Асимметрия с cartva (label:'cartva', без звёздочки) — сознательная:
// там источник (danda→d) уже прямо назван в самой сутре Панини. Footnote-
// пояснение звёздочки — в `#note` тестовой страницы; при интеграции в
// EXAMPLES[] перенести и в `roleDemo.text`/`GLOSSARY`.
//
// РАЗМЕР ПИЛЮЛЬ ШАГОВ ПО ЦЕЛЕВОМУ ПРАВИЛУ (напоминание принципа, не новый
// код в движке): чип шага (`.slot-step-chip`) большой (`primary:true`)
// только для ЦЕЛЕВОГО правила — того, ради которого открыт именно этот
// экран (EXAMPLES[8]/[9]/[31], в будущем — три разные точки входа в ОДИН
// и тот же 3D-модуль). `mount(container, {targetRuleNum})` — необязательный
// второй параметр: если задан, помечает `primary:true` ТОЛЬКО у шага с
// этим `ruleNum`, остальные два получают `primary:false` (тот же
// стандартный охровый `is-grammar`, что и любой вспомогательный шаг).
// Без параметра (текущее использование на тестовом полигоне) — все три
// остаются `primary:true`, как раньше, поведение не меняется.
import { mountSlotExample, centeredStart, TRANSFORM_KIND } from '../lib/slot-engine.js';

// Раскладка: centeredStart(8)=1 — совпадает с centeredStart(7)=1 (итоговое
