//  · Один кубик = один ЗВУК, не деванагари-буква. Обоснование — в предисловии
//    приложения («Почему звук, а не буква деванагари»).
//  · Ряд — 10 слотов, фиксированная камера, без адаптации под длину примера.
//  · Правила 61, 62, 64, 65 — сознательно не переводятся в 3D, только 2D.
//  · Операции — конечный список алгоритмов, пример = данные, не код.
//  · Все правки ниже — ОБЩИЕ свойства движка. Пример agnayas в
//    test-slot-engine.html — полигон для проверки, не цель сама по себе:
//    правим алгоритм на все будущие правила, не «причёсываем» один ролик.
//
// При смене буквы (transform) ВСЕ наборы материалов кубика (matsMain/
// matsBlank/matsReady/matsSignal) пересобираются заново под новый глиф
// (см. regenMats) — иначе «сигнальный»/«финальный» материал ещё долго
// хранит исходную, уже неактуальную букву, и на паузах/подходах на долю
// секунды снова показывается призрак старой буквы поверх новой.
//
// ШАГИ (`data.steps`) — явные границы между «грамматика» и «правило N» с
// автоматическим притенением фона по текущему шагу (кто активен — не
// притенён, кто нет — притенён), вместо того чтобы автору примера вручную
// рассчитывать пересекающиеся окна `dim`. Лента шагов под сценой и
// короткий маркер-вспышка в момент смены шага — часть того же механизма.
//
// Материал/геометрия кубика — не здесь, берутся из уже готового chalk-module.js.
//
// ФАЙЛ — ТОЧКА ВХОДА: реализация разбита на модули по смыслу
// (docs/app/lib/slot-engine-*.js), этот файл — тонкий barrel, реэкспортирует
// их целиком. Публичный API (что и как
// импортируют examples/*.js, тестовые HTML, приложение, tests/*.mjs) не
// изменился ни на одно имя — `import { X } from '../lib/slot-engine.js'`
// продолжает работать буквально как раньше, менять ничего не нужно.
//   slot-engine-core.js     — константы, токенизатор, цвета, плавность.
//   slot-engine-cube.js     — фабрика кубика: геометрия, материалы, тень.
//   slot-engine-words.js    — группы слов («вся единица, не одна буква»).
//   slot-engine-steps.js    — шаги (грамматика/правило N), runtime-таймлайн.
//   slot-engine-validate.js — валидация data перед первым кадром.
//   slot-engine-ops.js      — обработчики операций (apply*) и их помощники.
//   slot-engine-mount.js    — mountSlotExample: сцена, кадровый цикл, стили.
//   slot-engine-types.js    — JSDoc-типы (tsc --checkJs), не в барреле: ноль
//                             рантайм-экспортов, нечего реэкспортировать.

